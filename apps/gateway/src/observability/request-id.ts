/**
 * الغرض: **معرّفُ الطلبِ في كلِّ ردٍّ** — وسيطٌ يولّد معرّفاً لكلِّ طلبٍ ويعيده
 *   في رأسِ `X-Request-Id`، ليُربَط ما يراه المستخدمُ (حدثٌ أو خطأٌ في التطبيقِ
 *   المصغَّر) بما يراه المشغّلُ في الردّ. البند `F1-08`.
 * الحالة: منفّذ فعلياً — البند `F1-08`.
 * ينتمي إلى: apps/gateway/src/observability
 * يُتوقع أن يستخدمه لاحقاً: `apps/gateway/src/server.ts` وحدَه (موضعُ الوسيطِ
 *   الواحد)، و`F8-01` عندَ ربطِ التتبّعِ الموزَّعِ من الحافةِ إلى القاعدة.
 * ملاحظات مستقبلية: **ADR 0043** يقرّر أنّ الرأسَ اليومَ `X-Request-Id` يولّده
 *   الخادمُ وحدَه، وأنّ `traceparent` (W3C) قرارُ `F8-01` لا هذا البند. وحين
 *   يُركَّب OpenTelemetry يصير هذا الموضعُ جسرَ الربطِ لا موضعاً يُلغى.
 *
 * ثلاثةُ حدودٍ مقصودةٍ ههنا، وكلُّها من قرارِ مالكِ المنتجِ لا من اختيارِ منفِّذ:
 *   ــ **الخادمُ يولّد المعرّفَ وحدَه**: رأسُ `X-Request-Id` الوارِدُ من العميلِ
 *      **لا يُقرأ إطلاقاً**. وسببُه أنّ معرّفاً يرسله العميلُ مُدخَلٌ غيرُ موثوقٍ
 *      يُسجَّل ويُبحَث به، فيصير طريقاً لحقنِ السجلاتِ أو لتصادمِ المعرّفاتِ.
 *   ــ **لا يُسجَّل ههنا شيءٌ**: هذا الوسيطُ يعيد معرّفاً ولا يكتب سطراً. ولا
 *      طبقةَ سجلاتٍ مربوطةً بالمعرّفِ اليومَ (`OPS-002` مفتوح · `F8-01`).
 *   ــ **لا معرّفَ في جسمِ الردّ**: الرأسُ وحدَه. جسمُ الردِّ عقدٌ منشورٌ في
 *      القسم 10، وتغييرُه في هذا البندِ توسيعٌ للعقدِ بلا حاجة.
 *
 * **زيادةُ `F8-01` (2026-09-16 · `ح-8`: يُصحَّحُ بالإضافةِ ولا يُمحى ممّا سبقَ حرفٌ)**:
 * الشطرُ «ولا طبقةَ سجلاتٍ مربوطةً بالمعرّفِ اليومَ» **لم يبقَ قائماً**: هذا الوسيطُ
 * صارَ يُشغِّلُ بقيّةَ الطلبِ **داخلَ سياقِ ارتباطٍ محمولٍ**
 * (`packages/infrastructure/observability/correlation.ts`)، فالمُصدِرُ الوحيدُ للسجلِّ يُلحِقُ
 * المعرّفَ بكلِّ سطرٍ، و`withRequestContext` في عميلِ القاعدةِ ينقلُه إلى الصفِّ.
 * والحدُّ نفسُه قائمٌ في شقِّه الأوّلِ: **هذا الوسيطُ لا يكتبُ سطراً بنفسِه**.
 * وصيغةُ المعرّفِ لم تبقَ ههنا نسخةً ثانيةً بل تُستورَدُ من موضعِ الحقيقةِ
 * الواحدِ (القاعدة 0.6). و**رأسُ العميلِ الوارِدُ ما زالَ لا يُقرأُ ألبتّةَ**
 * — `ADR 0043` قائمٌ بحرفِه ولم يُنقَضْ، وحاجزٌ يحرسُه (`check-request-correlation`).
 */

import type { MiddlewareHandler } from "hono";
import {
  CORRELATION_ID_SHAPE,
  createCorrelation,
  runWithCorrelation,
} from "../../../../packages/infrastructure/observability/correlation.ts";

/** اسمُ الرأسِ — موضعُ الحقيقةِ الواحدُ لهذا الاسمِ في المستودعِ كلِّه. */
export const REQUEST_ID_HEADER = "X-Request-Id";

/**
 * الصيغةُ المقبولة: حروفٌ وأرقامٌ وشُرَطٌ، من 8 إلى 64 محرفاً. وهي أوسعُ من
 * UUID عن قصدٍ (ULID أو معرّفُ تتبّعٍ لاحقٌ يمرُّ)، وأضيقُ من «أيُّ نصٍّ»: الرأسُ
 * يُقرأ آلياً ويُبحَث به، ومحرفُ سطرٍ فيه يفسد كلَّ سجلٍّ يُبنى عليه لاحقاً.
 */
const ID_SHAPE = CORRELATION_ID_SHAPE;

function defaultGenerate(): string {
  return crypto.randomUUID();
}

/**
 * `generate` تُحقَن للاختبارِ وحدَه: للإنتاجِ مصدرٌ واحدٌ هو `crypto.randomUUID`.
 * ومُخرَجٌ لا يطابق الصيغةَ **يُطرَح ويُستبدَل بمعرّفٍ مولَّدٍ** ولا يمرُّ إلى
 * الرأس: حاجزٌ في مسارِ الطلبِ لا يجوز أن يُسقِط الطلبَ نفسَه، ولا أن يُخرِج
 * إلى الرأسِ ما لم يُتحقَّق من شكلِه.
 */
export function createRequestIdMiddleware(
  generate: () => string = defaultGenerate,
): MiddlewareHandler {
  return async (c, next) => {
    let id: string;
    try {
      const produced = generate();
      id = ID_SHAPE.test(produced) ? produced : defaultGenerate();
    } catch {
      id = defaultGenerate();
    }

    // رأسٌ مُعَدٌّ مسبقاً: يلحق كلَّ ردٍّ يُبنى عبرَ سياقِ Hono — بما فيه ردُّ
    // `notFound` وردُّ `onError`، وهما أهمُّ ردَّين يحتاج فيهما المشغّلُ معرّفاً.
    c.header(REQUEST_ID_HEADER, id);

    // السياقُ المحمولُ: كلُّ ما يجري داخلَ `next()` — سطرُ سجلٍّ أو استعلامُ قاعدةٍ
    // — يرى هذا المعرّفَ بلا تمريرِ وسيطٍ في كلِّ توقيعٍ. وبناءُ السياقِ يتحقّقُ من
    // الشكلِ ثانياً، **وغيابُ سياقٍ أصدقُ من سياقٍ مُلفَّقٍ**: لو رُدَّ المعرّفُ
    // (وذاكَ محالٌ ههنا لأنّه فُحِصَ أعلاهُ) يمضي الطلبُ بلا ارتباطٍ ولا يسقطُ —
    // وسيطُ مراقبةٍ لا يجوزُ أن يُسقِطَ الطلبَ الذي يراقبُه.
    const correlation = createCorrelation({ requestId: id, entry: "gateway" });
    if (correlation === null) {
      await next();
    } else {
      await runWithCorrelation(correlation, next);
    }

    // وردٌّ بُنِي خارجَ السياقِ (`new Response(...)` خامّاً في مسارٍ ما) لا يلحقه
    // الرأسُ المُعَدُّ، فيُلحَق ههنا بنسخةٍ لأنّ رؤوسَ بعضِ الردودِ غيرُ قابلةٍ
    // للتعديلِ في موضعِها. و«كلُّ ردٍّ» تعني كلَّ ردٍّ فعلاً لا أكثرَ الردود.
    if (!c.res.headers.has(REQUEST_ID_HEADER)) {
      const replacement = new Response(c.res.body, c.res);
      replacement.headers.set(REQUEST_ID_HEADER, id);
      c.res = replacement;
    }
  };
}
