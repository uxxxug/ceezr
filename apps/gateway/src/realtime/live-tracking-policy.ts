/** أسماءُ البيئاتِ التي يُمنَعُ فيها بثُّ الموقعِ الحيِّ منعاً باتّاً. */
export const LIVE_TRACKING_FORBIDDEN_ENVS = ["production"] as const;

/**
 * هل يُسمَحُ ببناءِ قناةٍ تبثُّ موقعَ السائقِ الحيَّ في هذه البيئةِ؟
 *
 * الإنتاجُ: `false` دائماً وبلا استثناءٍ ولا متغيِّرٍ يعكسُه.
 * غيرُه (`development` · `test`): `true` كي تبقى القناةُ قابلةً للقياسِ
 * والتطويرِ — فمنعُ الإنتاجِ حدٌّ، لا حذفٌ للميزةِ من المستودعِ.
 */
export function isLiveLocationBroadcastPermitted(env: string): boolean {
  return !(LIVE_TRACKING_FORBIDDEN_ENVS as readonly string[]).includes(env);
}
