/**
 * الغرض: منع معالجة التحديث نفسه أكثر من مرة عند إعادة إرسال تلغرام.
 * الحالة: منفّذ فعلياً.
 * ينتمي إلى: apps/gateway/src/routes
 * يُتوقع أن يستخدمه لاحقاً: مسار الويبهوك حصراً.
 *
 * ## لماذا في الذاكرة ولا في القاعدة — القرار وسنده
 *
 * قِستُ الضرر قبل اختيار الحلّ: أعدتُ إرسال تحديث «قبول عرض» بنفس
 * `update_id` على قاعدة حقيقية. **الحالة لم تتلف**: العروض المقبولة بقيت
 * واحداً والطلب بقي `matched`. والسبب أن الدوال الذرّية والقيود الفريدة
 * ومُهَل التهدئة تحمي الحالة أصلاً — `claim_ride` تردّ `ORDER_NOT_CLAIMABLE`،
 * وللتقييم قيد فريد، وللدعم تهدئة 300 ثانية.
 *
 * فالضرر المتبقّي **رسالة صادرة مكرَّرة** تُربك المستخدم، لا فسادُ بيانات.
 *
 * ولمّا كان هذا حجم الضرر، فجدولٌ في القاعدة بكتابة لكل تحديث ثمنٌ أكبر من
 * الفائدة: كتابة دائمة على كل نبضة مقابل منع رسالة مكرَّرة. فاختيرت ذاكرة
 * مقيَّدة الحجم: بلا تبعية جديدة، وبلا كتابة، وبلا مسار فشل إضافي.
 *
 * ## حدود هذا الحلّ — مذكورة لا مخفيّة
 *
 * 1. **يُفقد عند إعادة التشغيل.** فتحديثٌ يُعاد إرساله عبر إعادة تشغيل قد
 *    يُعالج ثانية. والأثر يبقى رسالة مكرَّرة لا فساداً، لما سبق.
 * 2. **لا يُشارَك بين النسخ.** صحيح الآن لأن `numInstances: 1` في
 *    `render.yaml`. **فإن رُفع العدد فوق واحد وجب مراجعة هذا الملفّ** —
 *    ولذلك اختبار يفشل إن تغيّر الإعداد، حتى لا يسقط الشرط صامتاً.
 * 3. ليس بديلاً عن الذرّية في القاعدة، بل طبقة راحة فوقها. لا يجوز إضعاف
 *    قفل أو قيد اتّكاءً عليه.
 *
 * ## الحالةُ اليوم: اختباريّةٌ وحدَها — لا مصدرُ قرارِ الإنتاج (SCL-001)
 *
 * مصدرُ قرارِ منعِ التكرارِ في الإنتاجِ هو **الإيداعُ الصامدُ في PostgreSQL**
 * (`claim_telegram_update`، ADR 0054): حجزُ إيصالٍ ذرّيٌّ على `(bot, update_id)`
 * مُوزَّعٌ بينَ النسخِ. و**هذا المانعُ الذاكرةُ يُستخدمُ في مسارِ التدهورِ وحدَه**
 * حينَ يغيبُ `intake` — وذاك **مسارُ اختبارٍ وقياسٍ لا يُ reachable في الإنتاج**
 * (`index.ts` يصلُ `intake` دائماً، وحاجزُ `requireDurableIntake` يرمي عند الإقلاعِ
 * إن غاب، ADR 0059/SCL-001). فلا يُعتَمدَ هذا المانعُ كـdedup للإنتاجِ، ولا يُعدَّ
 * بديلاً عن القاعدةِ في أيِّ تركيبٍ إنتاجيٍّ.
 */

/** سقف المفاتيح المحفوظة. عند بلوغه يُزاح الأقدم. */
export const DEDUP_MAX_KEYS = 10_000;

/**
 * عمر المفتاح. تلغرام يعيد المحاولة خلال دقائق، فساعة تغطّي ذلك بسعة.
 * وأطول من ذلك بلا فائدة: التحديث القديم لن يُعاد إرساله.
 */
export const DEDUP_TTL_MS = 60 * 60 * 1000;

export interface UpdateDeduplicator {
  /** `true` إن كان هذا التحديث جديداً (فيُعالَج)، و`false` إن كان مكرَّراً. */
  readonly admit: (bot: string, updateId: number) => boolean;
  readonly size: () => number;
}

/**
 * يُنشئ مانع تكرار مقيَّد الحجم والعمر.
 *
 * `Map` في جافاسكربت يحفظ ترتيب الإدخال، فأوّل مفتاح في التعداد هو الأقدم.
 * وهذا يكفي لإزاحة الأقدم بلا بنية بيانات إضافية.
 */
export function createUpdateDeduplicator(now: () => number = Date.now): UpdateDeduplicator {
  const seen = new Map<string, number>();

  return {
    admit(bot, updateId) {
      // المفتاح يضمّ البوت: لكل بوت عدّاد `update_id` مستقلّ عند تلغرام،
      // فبلا البوت يُلغى تحديثُ بوتٍ تحديثَ الآخر بالرقم نفسه.
      const key = `${bot}:${updateId}`;
      const at = now();

      const previous = seen.get(key);
      if (previous !== undefined) {
        if (at - previous < DEDUP_TTL_MS) return false;
        // انتهى عمره: يُعالَج ويُحدَّث وقته
        seen.set(key, at);
        return true;
      }

      seen.set(key, at);

      if (seen.size > DEDUP_MAX_KEYS) {
        // إزاحة الأقدم حتى نعود إلى السقف. حدٌّ صريح فلا تنمو الذاكرة بلا سقف
        const excess = seen.size - DEDUP_MAX_KEYS;
        let removed = 0;
        for (const oldest of seen.keys()) {
          seen.delete(oldest);
          removed += 1;
          if (removed >= excess) break;
        }
      }

      return true;
    },
    size: () => seen.size,
  };
}

/**
 * يستخرج `update_id` إن كان عدداً صحيحاً صالحاً.
 *
 * يُعيد `null` لما ليس كذلك، ومعناه عند المُستدعي: «لا تمنع» — فالأسلم أن
 * يُعالَج تحديثٌ مجهول الرقم مرّتين على أن يُرفض تحديثٌ شرعيّ.
 */
export function updateIdOf(update: object): number | null {
  const value = (update as { update_id?: unknown }).update_id;
  if (typeof value !== "number" || !Number.isInteger(value) || value < 0) return null;
  return value;
}
