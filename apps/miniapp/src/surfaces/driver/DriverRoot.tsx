import { useState } from "react";
import { EmptyState } from "../../system/EmptyState.tsx";
import { DocumentsScreen } from "./documents/DocumentsScreen.tsx";

type DriverView = "documents" | "placeholder";

export default function DriverRoot() {
  const [view, setView] = useState<DriverView>("documents");

  if (view === "documents") {
    return <DocumentsScreen onBack={() => setView("placeholder")} />;
  }

  return (
    <section aria-labelledby="driver-root-title">
      <h1 id="driver-root-title" style={{ margin: 0, fontSize: "1.5rem" }}>
        وَصْلة
      </h1>
      {/* `F1-07` — `UX-5`: حالةُ الفراغِ تُقال صراحةً ولا تُترَك بياضاً يُقرأ عطلاً. */}
      <EmptyState
        title="لا شيء يُعرَض بعد"
        body="شاشاتُ العملِ بنودُ F3، وهذا السطحُ فارغٌ عن قصدٍ. ووثائقُك تُدار في شاشةِ الوثائقِ."
      />
      <button type="button" className="dd__back" onClick={() => setView("documents")}>
        وثائقي
      </button>
    </section>
  );
}
