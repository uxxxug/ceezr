/**
 * الغرض: بابُ الهويةِ كما يراه الإطارُ — ثلاثُ دوالَّ يستدعيها `Shell` والموجّهُ
 *   بلا أن يستوردَ حزمةَ `identity`. والغرضُ **بنيويٌّ لا تجميليّ**: القسم 9.4
 *   يجعل `shell` و`identity` حزمتَين، وحزمتانِ تستوردُ كلٌّ منهما الأخرى تُنتجان
 *   دائرةً في مُخرَجِ البناءِ حذّر منها الجامعُ صريحاً.
 * الحالة: منفّذ فعلياً — البند `F1-09` (ADR 0044).
 * ينتمي إلى: apps/miniapp/src/shell (حزمة `shell` — القسم 9.4)
 * يُتوقع أن يستخدمه لاحقاً: `App.tsx` (يبني البابَ من الدوالِّ الحقيقيّة)،
 *   و`Shell.tsx` و`routing/RoleRouter.tsx` (يستدعيان عبرَه)، وكلُّ اختبارٍ يريد
 *   إقلاعاً بلا شبكةٍ ولا تيليجرام.
 * ملاحظات مستقبلية:
 *   - الأنواعُ ههنا مستوردةٌ من `identity` **بوصفِها أنواعاً فقط**، فتُمحى عند
 *     البناءِ ولا تُنشئ حرفاً واحداً من تبعيّةٍ في المُخرَج. وهذا هو الفرقُ بين
 *     معرفةِ الشكلِ ومعرفةِ التنفيذ.
 *   - هذا **ليس طبقةَ تجريدٍ للتبديل**: لا يوجد ولا يُتوقَّع مُنفِّذٌ ثانٍ لهويةٍ.
 *     من أراد إضافةَ دالّةٍ ههنا فليسأل أوّلاً: هل الإطارُ هو مَن يستدعيها؟
 *
 * لماذا الحقنُ لا الاستيراد: كان `Shell.tsx` يستورد `establishSession` و
 * `clearSession`، و`RoleRouter.tsx` يستورد `fetchViewer`. فحين فُصِلت `identity`
 * حزمةً كما يأمر القسم 9.4، ظهرت الدائرةُ `identity → shell → identity` في
 * البناء. والحلُّ ليس إعادةَ دمجِ الحزمتَين (نقضٌ للعقد) ولا إسكاتَ التحذيرِ
 * (إخفاءُ العَطَل)، بل قلبَ الاتجاه: الإطارُ يُعلِن ما يحتاجه، ونقطةُ الدخولِ —
 * وهي فوقَ الحزمتَين معاً — تُوصِل الحقيقيَّ به.
 */

import type { BootDeps, BootResult } from "../identity/boot.ts";
import type { ViewerView } from "../identity/viewer.ts";

export interface IdentityPort {
  /** إقامةُ الجلسةِ: جلسةٌ قائمةٌ، أو تجديدٌ من التخزينِ الآمنِ، أو مبادلةُ `initData`. */
  readonly establishSession: (deps?: BootDeps) => Promise<BootResult>;
  /** طرحُ ما في الذاكرةِ قبلَ إعادةِ مصادقةٍ — بلا هذا تعود «جلسةٌ قائمة». */
  readonly clearSession: () => void;
  /** قراءةُ الدورِ من الخادمِ. ولا يُقرأ الدورُ من حاملِ الجلسةِ ولا من تيليجرام (9.8). */
  readonly fetchViewer: () => Promise<ViewerView>;
}
