/**
 * الغرض: رابطُ العودةِ إلى بوتِ وَصْلة لشاشةِ «خارجَ تيليجرام» — الخطوةُ السادسةُ
 *   من ترتيبِ المالكِ بعدَ `DEC-07`: صفحةٌ سليمةٌ **وزرٌّ للعودةِ إلى البوتِ**.
 * الحالة: منفّذ فعلياً — البند `F1-07` / `F0-04` (شاشةُ خارجِ تيليجرام).
 * ينتمي إلى: apps/miniapp/src/system (حزمة `shell`)
 *
 * **لماذا متغيّرُ بناءٍ ولا نداءُ خادمٍ؟** هذه الشاشةُ تُعرَضُ **بلا جلسةٍ ولا
 * مضيفِ تيليجرامَ**، وهي أصلًا حالةُ «شيءٌ لم يعملْ». ونداءُ خادمٍ ههنا يلزمُه
 * مسارٌ عامٌّ جديدٌ بلا مصادقةٍ، وله عطلُه الخاصُّ الذي يجعلُ الشاشةَ تفشلُ مرّتَينِ.
 * فالقيمةُ تُخبَزُ في البناءِ كما يُخبَزُ `VITE_WASLAH_API_BASE`.
 *
 * **والكلفةُ تُعلَنُ لا تُخفى**: اسمُ البوتِ له مصدرُ حقيقةٍ آخرُ في الخادمِ
 * (`telegram-join-gate.ts` يقرأُه من `getMe`)، فهذا **مصدرٌ ثانٍ يفترقُ عنه بسهوٍ**
 * إن أُعيدَ تسميةُ البوتِ ولم يُحدَّثِ المتغيّرُ. والمخفِّفُ أنَّ أثرَ الافتراقِ
 * رابطٌ إلى بوتٍ لا يوجدُ — وهو ظاهرٌ فورًا للمستخدمِ الأوّلِ — لا خرقُ هويةٍ.
 *
 * **ولا يُعرَضُ زرٌّ لا يعملُ**: إن غابَ المتغيّرُ أو لم يكن رابطَ `t.me` صحيحًا
 * رجعَ `null`، **والشاشةُ تعرضُ نصَّها بلا زرٍّ**. زرٌّ معطَّلٌ أو زرٌّ يفتحُ لا شيءَ
 * أسوأُ من لا زرٍّ.
 */

/** المضيفُ الوحيدُ المأذونُ له — روابطُ تيليجرامَ وحدَها، لا نطاقَ آخرَ. */
const TELEGRAM_LINK_HOST = "t.me";

/**
 * يُقرأُ مرّةً واحدةً: قيمةُ زمنِ بناءٍ لا تتغيّرُ في زمنِ التشغيلِ، وقراءتُها
 * في كلِّ رسمٍ توحمُ بأنَّها قد تتبدّلُ.
 */
let cached: string | null | undefined;

/**
 * يُتحقَّقُ من الرابطِ بـ`URL` لا بمطابقةِ نصٍّ: `https://t.me/...` وحدَه يُقبَلُ.
 * فـ`javascript:` و`data:` ونطاقٌ يُنهي باسمِ `t.me` خِداعًا كلُّها تسقُطُ،
 * ورابطٌ يكتبه إنسانٌ في لوحةِ نشرٍ **مُدخَلٌ غيرُ موثوقٍ** ولو كتبَه مالكُ النظامِ.
 */
export function parseBotLink(raw: string | undefined): string | null {
  if (raw === undefined) return null;
  const trimmed = raw.trim();
  if (trimmed === "") return null;
  let parsed: URL;
  try {
    parsed = new URL(trimmed);
  } catch {
    return null;
  }
  if (parsed.protocol !== "https:") return null;
  if (parsed.hostname !== TELEGRAM_LINK_HOST) return null;
  // ‏`https://t.me` وحدَه بلا اسمٍ يفتحُ صفحةَ تيليجرامَ لا بوتَنا — ليسَ رابطَ عودةٍ.
  if (parsed.pathname === "/" || parsed.pathname === "") return null;
  return parsed.toString();
}

/** رابطُ العودةِ إلى البوتِ، أو `null` فلا يُعرَضُ زرٌّ. */
export function botLink(): string | null {
  if (cached === undefined) cached = parseBotLink(import.meta.env.VITE_WASLAH_BOT_LINK);
  return cached;
}

/** لِلاختبارِ وحدَه: يُنسى المحفوظُ فتُقرأَ قيمةٌ أخرى. */
export function resetBotLinkCacheForTests(): void {
  cached = undefined;
}
