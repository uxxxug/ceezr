/**
 * الغرض: مُسلسِلُ عملياتٍ لكلِّ مفتاح — يمنع تنفيذَ عمليتين لنفسِ المفتاحِ معاً.
 * الحالة: منفّذ فعلياً — وحدة 2-6.
 * ينتمي إلى: bench/topology
 * يُتوقع أن يستخدمه لاحقاً: أيُّ سحبٍ أو مزامنةٍ من نسخةٍ واحدةٍ بمؤشّرٍ متغيّر.
 *
 * ولماذا يستحقُّ ملفّاً ودالةً باسمٍ صريح: العطبُ الذي أوجدَه كان في **أداةِ القياس**
 * لا في النظامِ المقيس. خمسةُ فاعلين متزامنين سحبوا رسائلَ نفسِ البوّابةِ في اللحظةِ
 * نفسِها، فقرأت كلُّ عمليةِ سحبٍ نفسَ المؤشّر واستوعبت نفسَ الرسائلِ مرّةً أخرى:
 * ٤٠ رسالةَ عرضٍ مقابلَ ٢٥ عرضاً في القاعدة. وكان الحكمُ «إخفاقُ عمل» على نظامٍ
 * سليم. فالمُسلسِلُ هنا شرطُ صحّةِ قياسٍ لا تحسينُ أداء، ولذلك يُختبَر وحدةً.
 */

export interface KeyedSerializer {
  /** ينفّذ `task` بعد انتهاءِ كلِّ ما سُجّل قبلَه لنفسِ المفتاح. */
  run<T>(key: string, task: () => Promise<T>): Promise<T>;
}

export function createKeyedSerializer(): KeyedSerializer {
  const tails = new Map<string, Promise<unknown>>();

  return {
    run: async <T>(key: string, task: () => Promise<T>): Promise<T> => {
      const previous = tails.get(key) ?? Promise.resolve();
      /**
       * الذيلُ المحفوظُ مُبتلِعٌ للأخطاء عن قصد: عمليةُ سحبٍ فشلت لا يجوز أن تُسقط
       * كلَّ ما بعدها في نفسِ الطابور، ولا أن تُنتج `unhandled rejection` من ذيلٍ
       * لا ينتظره أحد. والخطأُ نفسُه يبقى مرئيّاً لصاحبِ الاستدعاء وحدَه.
       */
      const current = previous.then(task, task);
      tails.set(
        key,
        current.catch(() => undefined),
      );
      return await current;
    },
  };
}
