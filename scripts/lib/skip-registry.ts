  /** اسمُ متغيّرِ البيئةِ الذي يُعلِّق التجاوزَ — والحاجزُ يتحقّق أنّ الملفَّ يقرؤه. */
  readonly gate: string;
  readonly reason: string;
  readonly activation: string;
  readonly owner: SkipOwner;
  readonly criticalPath: CriticalPath | null;
  /** اسمُ خطوةِ CI التي تُشغِّله فعلاً، أو `null` إن لم يُشغِّله شيءٌ اليوم. */
