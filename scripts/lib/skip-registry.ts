/**
 * # سجلُّ التجاوزِ المُصنَّف — القائمةُ المغلقةُ الوحيدة
 *
 * **الغرض:** أن يكون في المستودعِ موضعٌ **واحدٌ** يُعلَن فيه كلُّ اختبارٍ يُتجاوَز،
 * ومعه أربعةُ أشياءَ لا يمرّ مدخلٌ بلا واحدٍ منها: **سببُ** التجاوزِ، و**شرطُ
 * تفعيلِه**، و**مالكُه**، و**المسارُ الحرجُ** الذي يخدمه إن كان يخدم واحداً. ثم
 * حيثُ يعمل فعلاً (`runsIn`) — أو بيانٌ مكتوبٌ أنّه لا يعمل في مكانٍ (`whyNotRun`).
 *
 * **الحالة:** `OPS-009` — مُنفَّذ · مُختبَر (ADR 0046). والأعدادُ **مقيسةٌ** بتشغيلِ
 * كلِّ ملفٍّ منفرداً يومَ 2026-08-29: خمسةٌ وخمسون ملفّاً و**514** حالةً متجاوَزةً،
 * وهو العددُ نفسُه الذي يذكره البندُ في القسم 11-د. ثمّ زاد يومَ 2026-08-30 مدخلٌ
 * سادسٌ وخمسون باثنتَي عشرةَ حالةً مقيسةً — ملفُّ `OPS-006` الذي يعمل على Redis حقيقيٍّ في
 * وظيفتِه وحدَها ويُتجاوَز حيث لا نقطةَ له، فصار المجموعُ **526**. ثمّ زاد يومَ
 * 2026-09-02 مدخلٌ سابعٌ وخمسون بثمانِ حالاتٍ مقيسةٍ — حزمةُ ترتيبِ أحداثِ التتبُّعِ
 * (`BUG-009`) التي شرطَ `ADR 0053 §٨` قاعدةَ PostgreSQL حقيقيّةً لحالتَيها ١ و٧،
 * فصار المجموعُ **534**. والزيادةُ تُعلَن
 * ولا تُدمَج في رقمِ `OPS-009`: ذاك قياسُ يومِه لا سقفٌ للمستودعِ.
 *
 * **ينتمي إلى:** البند `OPS-009` · القسم 11-د · القيدَ «لا يُطلَق تجارياً وبها
 * تجاوزٌ على مسارٍ حرج».
 *
 * **يُتوقع أن يستخدمه لاحقاً:** `scripts/check-skip-classification.ts` (يطابقه
 * بالشيفرةِ وبملفِّ سيرِ العمل) · `scripts/check-no-skipped-tests.ts` (يطابقه
 * بمخرجاتِ التشغيلِ الحقيقيّ) · واختباراتُ الوحدة.
 *
 * **ملاحظات مستقبلية:** كلُّ ملفِّ اختبارٍ جديدٍ فيه تجاوزٌ يُضاف ههنا أو يسقط
 * البناء. ومتى صار لقاعدةِ القياسِ مُشغِّلٌ في CI انتقل مدخلُ `bench-reset-seed`
 * من `whyNotRun` إلى `runsIn` — ولا يُحذَف البيانُ بل يُستبدَل بمُشغِّلٍ.
 *
 * **ما لا يفعله هذا الملفُّ عن قصدٍ — وحدودُه مُعلَنةٌ لا مضمرةٌ:**
 * - **ليس إذناً بالتجاوز.** التسجيلُ يُخرِج التجاوزَ من الصمتِ إلى العلن؛ ولا
 *   يُبرِّره. والتجاوزُ على مسارٍ حرجٍ بلا مُشغِّلٍ **يُسقِط البناءَ** ولا يُقبَل مدخلاً.
 * - **لا يفرض عددَ الحالات.** `skipped` مقيسٌ يومَ التصنيفِ ومرجعٌ للقارئ؛ ولو
 *   فُرِض لأسقطت كلُّ حالةٍ جديدةٍ البناءَ فضُغِط على تخفيفِ الحاجزِ نفسِه.
 * - **لا يعرف شيئاً عن البيئةِ ولا يقرأ قرصاً.** بياناتٌ مُجمَّدةٌ فقط.
 * - **لا يحرس شيئاً.** الفرضُ في الحاجزَين وحدَهما.
 */

