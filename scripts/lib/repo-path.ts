/**
 * الغرض: توحيدُ فاصلِ المسار إلى `/` في كلِّ بوّابةٍ تقارن مساراً بنصٍّ مكتوب.
 * الحالة: منفّذ فعلياً — أُضيف في 2026-08-14.
 * ينتمي إلى: scripts/lib
 * يُتوقع أن يستخدمه لاحقاً: كلُّ فاحصٍ في scripts يجمع ملفّاتٍ بـ`join` ثمّ
 *   يقارنها بقائمةِ استثناءٍ أو يفحص بادئتَها.
 * ملاحظات مستقبلية: لا تُضاف هنا منطقيّةُ فحصٍ. هذه الوحدةُ سطرٌ واحدٌ بقصد:
 *   وحدةٌ تتضخّم تصير مكاناً يُخبَّأ فيه استثناءٌ عن عينِ المراجع.
 *
 * لماذا وُجِدت: `join` في Windows يُنتج `scripts\x.ts` لا `scripts/x.ts`. وكلُّ
 * بوّابةٍ تحمل قائمةَ استثناءٍ مكتوبةً بـ`/` كانت تُخفق هناك بطريقتين، وكلتاهما
 * أسوأُ من عدمِ الفحص:
 *   (١) استثناءٌ لا يُطابَق، فيصرخ الفاحصُ على الملفّ الذي كُتب الاستثناءُ له —
 *       وهذا وقع فعلاً: `check-map-matching-scope` صرخ على تعريفِ أنماطِه في نفسِه
 *       وأسقط `bun run ci` على جهازِ المالك، بلا أيّةِ مخالفةٍ حقيقيّة.
 *   (٢) وحاجزٌ يسقط سقوطاً كاذباً على كلِّ من يُشغّله على Windows هو حاجزٌ
 *       يُعطَّل أو يُحذَف في أوّلِ أسبوع، فتُفتح الثغرةُ التي كُتب لإغلاقها.
 * فالتوحيدُ عند جمعِ الملفّات لا عند المقارنةِ وحدها، كي تكون رسالةُ الخطأ
 * نفسَها في كلِّ نظامِ تشغيل ولا يتباعد ما يُفحَص عمّا يُطبَع.
 */

export function toPosixPath(path: string): string {
  return path.split("\\").join("/");
}
