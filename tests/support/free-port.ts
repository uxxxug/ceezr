/**
 * الغرض: منفذٌ حرٌّ **يُسألُ منَ النظامِ** لكلِّ عمليّةٍ فرعيّةٍ يُقلعُها اختبارٌ،
 *   بدلَ رقمٍ يُحسَبُ من `process.pid` فيبدو فريداً وهوَ ليسَ كذلك.
 * الحالة: منفّذ فعلياً — `ADR 0100`.
 * ينتمي إلى: tests/support
 * يُتوقع أن يستخدمه لاحقاً: كلُّ اختبارٍ يُقلعُ بوّابةً أو لوحةً أو خادماً على منفذٍ.
 * ملاحظات مستقبلية: لو احتيجَ حجزٌ يبقى قائماً حتى يستلمَه الوليدُ (`SO_REUSEPORT`
 *   بتمريرِ المقبسِ نفسِه) فذاكَ تغييرٌ في واجهةِ الإقلاعِ لا في هذا الملفِّ.
 *
 * ولماذا لا يُحسَبُ المنفذُ؟ لأنّ الحسابَ من `process.pid` يمنعُ التعارضَ بينَ
 * حالاتِ الملفِّ الواحدِ **ولا يمنعُه بشاغلٍ آخرَ على العاملِ نفسِه**: لا وكيلَ
 * قياسٍ ولا خدمةَ حاوياتٍ ولا ملفَّ اختبارٍ آخرَ. وحينَ يُصطدَمُ يموتُ الوليدُ
 * بـ`EADDRINUSE` فيبقى المُختبَرُ ينتظرُ صحّةً لا تجيءُ، **فيُقرأُ العطلُ مهلةً
 * وهوَ منفذٌ مشغولٌ** — وهذا بعينِه ما أخفقَ في الشغلتَين `34734754215`
 * و`34736418060`. والنظامُ وحدَه يعلمُ ما هوَ حرٌّ الآنَ، فيُسألُ.
 */

/**
 * يحجزُ منفذاً عابراً ثمّ يُخليه فوراً ويعيدُ رقمَه.
 *
 * وبينَ الإخلاءِ والإقلاعِ نافذةٌ يستحيلُ إغلاقُها بلا تمريرِ المقبسِ إلى الوليدِ،
 * فتبقى **مسابقةً ممكنةً نظريّاً** — ولذا يُقرنُ هذا بإعادةِ إقلاعٍ عندَ
 * `EADDRINUSE` وحدَه في موضعِ الاستدعاءِ. أمّا احتمالُ التعارضِ فقد صارَ من
 * «مؤكَّدٌ متى تصادفَ رقمانِ محسوبانِ» إلى «نافذةٌ من أجزاءِ الثانيةِ».
 */
export function reserveFreePort(): number {
  const probe = Bun.listen({ hostname: "127.0.0.1", port: 0, socket: { data() {} } });
  const port = probe.port;
  probe.stop(true);
  return port;
}
