/**
 * الغرض: معجمُ أسبابِ إبطالِ جلساتِ Mini App **مغلقاً** — مصدرُ حقيقةٍ واحدٌ
 *   يقرؤهُ مسلكُ اللوحةِ، ويُطابِقُهُ حاجزٌ بنصِّ الهجرةِ (`SEC-18-ب`).
 * الحالة: منفَّذٌ — البند `SEC-18` (ساقُ سجلِّ القرارِ).
 * ينتمي إلى: application/identity
 * يُتوقَّعُ أن يستخدمَهُ: apps/gateway/src/routes/admin-ui.ts و
 *   tests/unit/session-revocation-reasons.test.ts.
 * الحاكم: ADR 0174 · سابقةُ `PD-021` (سببٌ إلزاميٌّ من معجمٍ مغلقٍ)
 *
 * ## ولِمَ معجمٌ مغلقٌ لا نصٌّ حرٌّ
 *
 * سببٌ حرٌّ يُكتَبُ فراغاً أو «test» أو «.» — فيصيرُ العمودُ يقبلُ ما يُمرَّرُ،
 * **وسجلٌّ لا يُميِّزُ عدّادٌ**. والمطلوبُ من سجلِّ القرارِ أن يُجيبَ «لِمَ أُبطِلَت
 * هذه الجلسةُ» بعدَ شهرٍ، ولا يُجيبُ ذلكَ نصٌّ حرٌّ لم يُقرأ حينَ كُتِبَ.
 *
 * ## ولِمَ يُكرَّرُ المعجمُ في الهجرةِ وههنا
 *
 * القاعدةُ هي السلطةُ (`security definer`)، فلو وُثِقَ بفحصِ المسلكِ وحدَهُ لمرَّ
 * سببٌ غيرُ مُعجَميٍّ من أيِّ مُتصِلٍ آخرَ. ولو فُحِصَ في القاعدةِ وحدَها لأُنفِذَ
 * الإبطالُ **قبلَ** أن يُرفَضَ السببُ — إذ الإنفاذُ يسبقُ التسجيلَ (`ADR 0174`).
 * فالفحصُ في الموضعَينِ، **والانحرافُ بينَهما محروسٌ لا مأمولٌ**: اختبارُ وحدةٍ
 * يقرأُ نصَّ الهجرةِ ويُطابِقُ المجموعتَينِ حرفاً بحرفٍ.
 */

/**
 * أسبابُ الإبطالِ المقبولةُ. ليسَت رسائلَ للمستخدمِ بل **رموزُ قرارٍ داخليّةٌ**:
 * تُكتَبُ في `audit_log` ولا تُعادُ إلى صاحبِ الجلسةِ (سابقةُ `PD-021`: العلنُ لا
 * يُفشي السببَ الداخليَّ).
 */
export const SESSION_REVOCATION_REASONS = [
  /** الجهازُ مسروقٌ أو مفقودٌ — أبلغَ صاحبُه أو أبلغَ عنه. */
  "stolen_device",
  /** انكشافُ بيانِ نفاذٍ: رمزٌ أو سرٌّ ظهرَ حيثُ لا ينبغي. */
  "credential_compromise",
  /** نشاطٌ مريبٌ على الحسابِ يقتضي قطعَ الجلساتِ قبلَ الفحصِ. */
  "suspicious_activity",
  /** طلبُ المستخدمِ نفسِه: «أخرِجني من كلِّ الأجهزةِ». */
  "user_request",
  /** تحقيقُ دعمٍ جارٍ يقتضي تثبيتَ الحالةِ. */
  "support_investigation",
] as const;

export type SessionRevocationReason = (typeof SESSION_REVOCATION_REASONS)[number];

const REASON_SET: ReadonlySet<string> = new Set<string>(SESSION_REVOCATION_REASONS);

/** أينتمي هذا النصُّ إلى المعجمِ؟ يُستعمَلُ في المسلكِ قبلَ أيِّ إنفاذٍ. */
export function isSessionRevocationReason(value: unknown): value is SessionRevocationReason {
  return typeof value === "string" && REASON_SET.has(value);
}
