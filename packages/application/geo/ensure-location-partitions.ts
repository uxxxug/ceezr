/**
 * الغرض: صيانةُ أقسامِ `driver_location_history` — منفذٌ وحالةُ استخدامٍ تُقدِّمانِ
 *   نافذةَ الأقسامِ اليوميّةِ أماماً قبلَ أن يحتاجَها كاتبٌ، وتقرآنِ عددَ صفوفِ
 *   القِسمِ الافتراضيِّ فتُظهرانِ العطلَ بدلَ أن يُبتلَعَ. البند `F7-03`، `ADR-0074`.
 * الحالة: منفّذ فعلياً — 2026-09-10 · البند `F7-03`.
 * ينتمي إلى: application/geo
 * يُستخدم من: `apps/workers/src/container.ts` (مهمّةٌ عامّةٌ يوميّةٌ، لا لكلِّ مدينةٍ).
 * ملاحظات مستقبلية: حذفُ الأقسامِ القديمةِ **ليسَ ههنا** — الاستبقاءُ بندُ `F7-06`،
 *   وخلطُه بالإنشاءِ يجعلُ مهمّةً واحدةً تملكُ الإنشاءَ والمحوَ معاً؛ وذاكَ ما لا
 *   يُراجَعُ بيُسرٍ حينَ يُخطئُ.
 *
 * ## لماذا مهمّةٌ أصلاً — والهجرةُ أنشأت أربعةَ عشرَ يوماً
 *
 * لأنَّ الهجرةَ تجري مرّةً والزمنَ يجري دائماً. فنافذةُ الهجرةِ تنفدُ بعدَ أسبوعينِ
 * من نشرِها، وبعدَها لا قِسمَ لليومِ الجاري. وبلا هذه المهمّةِ يكونُ بقاءُ كتابةِ
 * المواقعِ معتمداً على **نشرةٍ بشريّةٍ كلَّ أسبوعينِ** — وهوَ اعتمادٌ على تدخّلٍ
 * يدويٍّ في مسارٍ حارٍّ، والقاعدةُ ٥ من أولويّاتِ المسارِ ترفضُه.
 *
 * ## ولماذا عامّةٌ لا لكلِّ مدينةٍ
 *
 * القِسمُ يقعُ على `recorded_at` وحدَه، ومدىً زمنيٌّ واحدٌ يخدمُ المدنَ كلَّها.
 * فمهمّةٌ لكلِّ مدينةٍ تعني `n` نداءاتٍ متسابقةً تُنشئُ الجدولَ نفسَه — أوّلُها
 * ينجحُ وبقيّتُها تصطدمُ. والمقسِّمُ ليسَ خاصّيّةً للمدينةِ، فلا يُقسَّمُ العملُ
 * بها.
 *
 * ## ولماذا لا تسقطُ المهمّةُ حينَ يمتلئُ القِسمُ الافتراضيُّ
 *
 * لأنَّ صفّاً في القِسمِ الافتراضيِّ لا يمنعُ إنشاءَ أقسامِ **الغدِ** — إنّما يمنعُ
 * إنشاءَ قِسمِ اليومِ الذي ابتلعَ صفَه. فإسقاطُ المهمّةِ كلِّها يوقفُ تقديمَ
 * النافذةِ فيصنعُ العطلَ الأكبرَ علاجاً للأصغرِ. والحصيلةُ تحملُ العددَ، والمُنادي
 * يُسجِّلُه صريحاً في كلِّ دورةٍ.
 */

import type { Result } from "../../shared/result/index.ts";
import type { PortFailureError } from "../ports/index.ts";

/**
 * كم يوماً تُقدَّمُ النافذةُ. أربعةَ عشرَ: عطلُ عاملٍ أسبوعينِ كاملينِ حادثٌ
 * كبيرٌ يُرى في كلِّ لوحةٍ قبلَ أن يبلغَ أثرُه كتابةَ المواقعِ. وزيادتُها إلى
 * تسعينَ تُنشئُ تسعينَ جدولاً فارغاً يُثقلُ `pg_class` بلا مقابلٍ.
 */
export const LOCATION_PARTITION_DAYS_AHEAD = 14;

/** حصيلةُ شوطِ صيانةٍ — كما تُرجِعُها `ensure_driver_location_partitions`. */
export interface LocationPartitionReport {
  /** أسماءُ الأقسامِ التي أُنشئت في هذا الشوطِ — فارغةٌ في الشوطِ السويِّ الثاني. */
  readonly created: readonly string[];
  /** أقسامٌ وُجِدَت فلم تُمَسَّ. */
  readonly existing: number;
  /**
   * صفوفُ القِسمِ الافتراضيِّ. **صفرٌ هوَ الحالُ السويُّ الوحيدُ**: كلُّ صفٍّ ههنا
   * يعني إصلاحةً هبطت في شبكةِ الأمانِ لغيابِ قِسمِ يومِها.
   */
  readonly defaultRows: number;
}

/** منفذُ الصيانةِ: نداءٌ واحدٌ لدالّةٍ مُتماثِلةٍ، لا `DDL` في الشيفرةِ. */
export interface LocationPartitionMaintenance {
  ensurePartitions(daysAhead: number): Promise<Result<LocationPartitionReport, PortFailureError>>;
}

export interface EnsureLocationPartitionsDeps {
  readonly partitions: LocationPartitionMaintenance;
}

/**
 * شوطُ صيانةٍ واحدٌ. لا حسابَ ههنا ولا شكلَ قِسمٍ: شكلُ القِسمِ في الدالّةِ وحدَها
 * (`ADR-0074` §٤)، وما في هذه الطبقةِ اختيارُ النافذةِ وقراءةُ الحصيلةِ.
 */
export function ensureLocationPartitions(
  deps: EnsureLocationPartitionsDeps,
  daysAhead: number = LOCATION_PARTITION_DAYS_AHEAD,
): Promise<Result<LocationPartitionReport, PortFailureError>> {
  return deps.partitions.ensurePartitions(daysAhead);
}
