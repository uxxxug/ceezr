import type { SupportTicketType } from "../../domain/dispute/index.ts";

/** ما يُمرَّر للمستشار: أقلّ ما يكفيه. لا كائن تذكرة كامل ولا وصول للقاعدة. */
export interface TicketAdviceRequest {
  readonly ticketId: string;
  readonly type: SupportTicketType;
  readonly message: string;
  readonly cityId: string | null;
  readonly openedAt: string;
}

export interface TicketAdvice {
  /** معرّف التتبّع — يُستخدم لاحقاً لتسجيل ما فعله الفريق فعلاً بهذا الاقتراح. */
  readonly traceId: string;
  /** التصنيف الأوّلي كما رآه المستشار، أو `null` إن لم يُصنِّف. */
  readonly classification: string | null;
  /** النصّ المقترح. `null` يعني: لا اقتراح — وهي نتيجة صحيحة لا خطأ. */
  readonly suggestion: string | null;
  readonly confidence: number;
}

export interface TicketAdvisor {
  /**
   * **لا يرمي أبداً.** يُعيد `null` عند التعطيل أو الفشل أو انعدام الاقتراح —
   * والمستدعي لا يميّز بين هذه الحالات لأنه يتصرّف فيها التصرّف نفسه.
   */
  advise(request: TicketAdviceRequest): Promise<TicketAdvice | null>;
}
