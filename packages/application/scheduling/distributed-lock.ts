/**
 * الغرض: منفذ القفل الموزَّع الذي يمنع تنفيذ مهمّة دورية واحدة في نسختين من خدمة
 *   العامل في اللحظة نفسها. الطبقة التطبيقية تعرف أنها تحتاج «حصرية باسم»، ولا
 *   تعرف — ولا يجوز أن تعرف — أن التنفيذ في Postgres advisory lock.
 * الحالة: منفّذ فعلياً — القسم 1.
 * ينتمي إلى: application/scheduling
 * يُتوقع أن يستخدمه لاحقاً: apps/workers/src/container.ts، وأي مهمّة دورية جديدة
 * ملاحظات مستقبلية: لو انتقل التنفيذ إلى Redis يكفي محوّل جديد بنفس هذا العقد.
 */

/** نتيجة محاولة التنفيذ تحت القفل: إمّا نُفِّذ فله قيمة، أو لم يُنَل القفل فلا قيمة. */
export type LockAttempt<T> =
  | { readonly acquired: true; readonly value: T }
  | { readonly acquired: false };

export interface DistributedLock {
  /**
   * يحاول أخذ قفل باسم `key` ثم يُشغّل `run`. إن كان القفل مأخوذاً فلا ينتظر ولا
   * يعيد المحاولة: يُعيد `{ acquired: false }` فوراً.
   *
   * الانتظار خطأ هنا لا تحسين: مهمّة دورية تأخّرت دورةً لا تخسر شيئاً — ستُشغَّل في
   * الدورة التالية بعد دقيقة. أمّا الانتظار فيُراكم نسخاً عالقة على قفل واحد حتى
   * ينفد التجمّع، فيسقط ما كان يعمل من أجل ما لم يكن ضرورياً.
   *
   * لا يرمي إن رمى `run`: تحرير القفل مضمون، والخطأ يُعاد رفعه بعد التحرير.
   */
  withLock<T>(key: string, run: () => Promise<T>): Promise<LockAttempt<T>>;
}

/**
 * قفل لا يقفل شيئاً — للاختبار وللتشغيل بنسخة واحدة عن قصد صريح.
 * وجوده مُعلَن حتى لا يُستخدم بالخطأ في الإنتاج ظنّاً أنه القفل الحقيقي.
 */
export function createNoopLock(): DistributedLock {
  return {
    withLock: async (_key, run) => ({ acquired: true, value: await run() }),
  };
}
