/**
 * جداولُ صنفِ `domain-ingress receipt`. **قائمةٌ مغلقةٌ** بمُدخلٍ واحدٍ اليوم.
 *
 * `telegram_update_receipts`: سجلُّ استلامِ تحديثاتِ تيليجرام. لا مدينةَ له لحظةَ
 * الاستلام لأنّ القرارَ يسبق أيَّ تفسيرٍ للحمولةِ — فما ليس مقروءاً بعدُ لا يُنسَب
 * إلى مدينةٍ إلّا باشتقاقٍ اصطناعيٍّ، وهو المنهيُّ عنه في الملحقِ نفسِه.
 */
export const DOMAIN_INGRESS_RECEIPT_TABLES = ["telegram_update_receipts"] as const;

export type DomainIngressReceiptTable = (typeof DOMAIN_INGRESS_RECEIPT_TABLES)[number];

/**
 * الصيغةُ المُثبَّتةُ التي يجب أن تظهر في نصِّ الهجرةِ لإعلانِ انتماءِ جدولٍ إلى الصنف.
 * يُقرأ منها الاسمُ ويُطابَق بالقائمةِ أعلاه، فلا يُعفى جدولٌ بتصريحٍ بلا إعلانٍ ولا
 * بإعلانٍ بلا تصريح. تُبنى هنا في موضعٍ واحدٍ كي لا يختلف الحارسُ عن الهجرةِ حرفاً.
 */
export const DOMAIN_INGRESS_RECEIPT_DECLARATION_PREFIX = "-- domain-ingress-receipt:";

/** التصريحُ الحرفيُّ الواجبُ في هجرةِ جدولٍ من الصنف. */
export function domainIngressReceiptDeclaration(table: DomainIngressReceiptTable): string {
  return `${DOMAIN_INGRESS_RECEIPT_DECLARATION_PREFIX} ${table}`;
}

/** هل الاسمُ مُعلَنٌ في القائمةِ المغلقة؟ */
export function isDomainIngressReceiptTable(name: string): name is DomainIngressReceiptTable {
  return (DOMAIN_INGRESS_RECEIPT_TABLES as readonly string[]).includes(name);
}

