/**
 * الغرض: إعلانُ صنفِ `platform secret` — القائمةُ المغلقةُ الثانيةُ لجداولَ يجوزُ
 *    لها ألّا تحملَ `city_id`، وفقَ **الملحقِ الحاكمِ 2026-09-14** في
 *    [`docs/MASTER_DIRECTIVE.md`](../../../docs/MASTER_DIRECTIVE.md).
 * الحالة: منفّذ فعلياً — إعلانٌ يقرؤه حارسُ `scripts/check-migrations.ts`.
 * ينتمي إلى: shared/config
 * يُتوقع أن يستخدمه لاحقاً: `scripts/check-migrations.ts`
 * ملاحظات مستقبلية: إضافةُ اسمٍ ثالثٍ هنا **لا تكفي** — الصنفُ مغلقٌ كسابقِه،
 *    وتوسيعُه يقتضي ملحقاً حاكماً جديداً لا ADR ولا تعليقاً في هجرةٍ.
 *
 * ## لماذا صنفٌ ثانٍ ولم يُوسَّع الأوّلُ
 *
 * صنفُ `domain-ingress receipt` عِلّتُه **الزمنُ**: الصفُّ يُكتَبُ قبلَ أن
 * تُقرأَ حمولتُه، فلا مدينةَ معروفةً بعدُ. وعِلّةُ هذا الصنفِ **المرتبةُ**:
 * الصفُّ ليسَ بيانةَ مدينةٍ أصلاً بل سرَّ النشرِ كلِّه. ولو أُدخِلَ الثاني في
 * الأوّلِ لَصارَ اسمُ الصنفِ كذباً على مضمونِه، ولَفتحَ بابَ «كلُّ ما عسُرَ عليه
 * `city_id` فهوَ إيصالُ استلامٍ» — وذاكَ عينُ التوسيعِ الذي أُغلِقَ الصنفُ
 * الأوّلُ لمنعِه. فالفصلُ ههنا **تضييقٌ لا توسيعٌ**.
 *
 * ## شرطُ الانتماءِ مزدوجٌ كسابقِه
 *
 * اسمٌ في القائمةِ المغلقةِ أدناه، **و**تصريحٌ حرفيٌّ في الهجرةِ التي تُنشئُ
 * الجدولَ. فلا يُعفى جدولٌ بإحداهما وحدَها، ولا يُوسَّعُ الصنفُ بتعليقٍ.
 *
 * ## ما لا يُعفى منه هذا الصنف
 *
 * `RLS` لا تسقط. والصلاحيّاتُ تُنزَعُ نزعاً صريحاً عن `public` و`anon`
 * و`authenticated`، فلا يبلغُ السرَّ إلّا `security definer`. ولا يجوزُ لجدولٍ
 * في هذا الصنفِ أن يحملَ **بيانةَ إنسانٍ البتّةَ**: سرٌّ وحدَه، وإلّا سقطَ
 * الإعفاءُ من أصلِه لأنَّ حُجّتَه «لا صفَّ فيه لأحدٍ».
 */

/**
 * جداولُ صنفِ `platform secret`. **قائمةٌ مغلقةٌ** بمُدخلٍ واحدٍ اليومَ.
 *
 * `identity_hash_pepper`: فِلفِلُ تجزئةِ الهُويّةِ (`ADR 0113`). صفٌّ واحدٌ
 * أبديٌّ يحملُ ٢٥٦ بتّاً عشوائيّةً تُشتَقُّ بها تجزئةُ `identity_marks`. لا
 * ينتمي إلى مدينةٍ لأنَّ الأثرَ الذي يحرسُه **يَعبُرُ المدنَ عمداً**: مَن حُظِرَ
 * في جُدّةَ لا يُستأنَفُ حظرُه في مكّةَ. ولو نُسِبَ الفِلفِلُ إلى مدينةٍ لَلزِمَ
 * إمّا فِلفِلٌ لكلِّ مدينةٍ — فتنقطعُ المطابقةُ عبرَها ويُفتَحُ بابُ التنصُّلِ
 * بتغييرِ المدينةِ — أو فِلفِلٌ واحدٌ منسوبٌ إلى مدينةٍ لا يخصُّها، وهوَ كذبٌ
 * في المخطّطِ يُقرأُ صِدقاً.
 */
export const PLATFORM_SECRET_TABLES = ["identity_hash_pepper"] as const;

export type PlatformSecretTable = (typeof PLATFORM_SECRET_TABLES)[number];

/**
 * الصيغةُ المُثبَّتةُ التي يجب أن تظهر في نصِّ الهجرةِ لإعلانِ انتماءِ جدولٍ إلى
 * الصنفِ. تُبنى ههنا في موضعٍ واحدٍ كي لا يختلفَ الحارسُ عن الهجرةِ حرفاً.
 */
export const PLATFORM_SECRET_DECLARATION_PREFIX = "-- platform-secret:";

/** التصريحُ الحرفيُّ الواجبُ في هجرةِ جدولٍ من الصنف. */
export function platformSecretDeclaration(table: PlatformSecretTable): string {
  return `${PLATFORM_SECRET_DECLARATION_PREFIX} ${table}`;
}

/** هل الاسمُ مُعلَنٌ في القائمةِ المغلقة؟ */
export function isPlatformSecretTable(name: string): name is PlatformSecretTable {
  return (PLATFORM_SECRET_TABLES as readonly string[]).includes(name);
}
