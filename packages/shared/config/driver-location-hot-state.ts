/**
 * الغرض: سجلُّ المسارِ الساخنِ لموقعِ السائقِ — **مصدرُ الحقيقةِ الواحدُ** لسؤالَينِ:
 *    أيُّ أرقامٍ يحتاجُها هذا المسارُ؟ وأينَ يسكنُ كلُّ رقمٍ منها؟ يقرؤه حارسُ
 *    `scripts/check-hot-location-state.ts` وكودُ التشغيلِ معاً. البند `F4-02`
 *    والعائقُ `CAP-009`.
 * الحالة: منفّذ فعلياً — 2026-09-09.
 * ينتمي إلى: shared/config
 * يُستخدم من: `packages/application/geo/driver-location-hot-state.ts`،
 *    `packages/infrastructure/geo/redis-driver-location-hot-state.ts`،
 *    `scripts/check-hot-location-state.ts`، `tests/unit/driver-location-hot-state.test.ts`
 * ملاحظات مستقبلية: إن أُضيفَ بُعدٌ خامسٌ للمسارِ الساخنِ (سقفُ نبضاتٍ لسائقٍ في
 *    الدقيقةِ مثلاً) فمكانُه هذه القائمةُ ثمَّ بذرُه في هجرةٍ، وإلّا سقطَ الحاجزُ.
 *
 * ## لماذا سجلٌّ لا أرقامٌ
 *
 * هذا الملفُّ **لا يحملُ رقماً واحداً**، وذلكَ عينُ القاعدةِ ٠.٣: كلُّ رقمٍ قابلٍ
 * للمعايرةِ يسكنُ `platform_settings` صفّاً لكلِّ مدينةٍ. ولو نُسِخَ رقمٌ ههنا
 * «افتراضاً للطمأنينةِ» لصارَ للحدِّ موضعانِ: من عايرَ الصفَّ في القاعدةِ ظنَّ أنّه
 * عايرَ النظامَ، والنظامُ يقرأُ نسخةَ الشيفرةِ. فما ههنا **عناوينُ** الأرقامِ.
 *
 * ## لماذا غيابُ المفتاحِ يُقرأُ خرقاً لا افتراضاً
 *
 * لو قُرِئَ الغيابُ بقيمةٍ افتراضيّةٍ في الشيفرةِ لكانَ خطأُ إعدادٍ واحدٌ يُشغِّلُ
 * المسارَ الساخنَ بأرقامٍ لا يعرفُها أحدٌ. فالغيابُ يُقرأُ خرقاً مُعلَناً: المسارُ
 * الساخنُ **يُعطَّلُ** ويُكتَبُ الموقعُ في القاعدةِ مباشرةً كما كانَ في `F4-01`،
 * ويُسجَّلُ السببُ. تدهوّرٌ مرئيٌّ لا صمتٌ، ولا سائقٌ يغيبُ عن الخريطةِ.
 * وثلاثةُ حُرّاسٍ قائمةٍ تجعلُ الغيابَ شبهَ مستحيلٍ: البذرُ في الهجرةِ، وتوريثُ
 * `cities_seed_settings`، ومنعُ `cities_require_complete_settings` تفعيلَ مدينةٍ
 * ينقصُها مفتاحٌ.
 */

/**
 * مفاتيحُ المسارِ الساخنِ الأربعةُ. **قائمةٌ مغلقةٌ** يُنفِذُها الحاجزُ ضدَّ
 * الهجراتِ: من زادَ مفتاحاً زادَ سطرَه ههنا وبذرَه في هجرةٍ، أو سقطَ الحاجزُ.
 */
export const HOT_LOCATION_SETTING_KEYS = [
  /** عمرُ الحالةِ الساخنةِ لموقعِ سائقٍ واحدٍ، ثوانيَ — بعدَه تُنسى فتُقرأُ القاعدةُ. */
  "driver_location_hot_ttl_seconds",
  /** دورةُ الإفراغِ المجمَّعِ إلى PostgreSQL، ثوانيَ. */
  "driver_location_flush_interval_seconds",
  /** أقصى ما يُفرَّغُ في شوطٍ واحدٍ — سقفُ الدفعةِ الواصلةِ إلى الدالّةِ الذرّيّةِ. */
  "driver_location_flush_batch_size",
  /** أقصى ما يتراكمُ في قائمةِ الانتظارِ قبلَ أن يُكتَبَ الموقعُ مباشرةً. */
  "driver_location_backlog_limit",
] as const;

export type HotLocationSettingKey = (typeof HOT_LOCATION_SETTING_KEYS)[number];

/**
 * اسمُ الدالّةِ الذرّيّةِ الواحدةِ التي تُطبِّقُ الدفعةَ. مُعلَنٌ ههنا لا مكتوبٌ
 * نصّاً في المحوّلِ وحدَه: الحاجزُ يبحثُ عنها في الهجراتِ بهذا الاسمِ بعينِه،
 * فاسمٌ يُغيَّرُ في موضعٍ ويُنسى في آخرَ يسقطُ في CI لا في الإنتاجِ.
 */
export const DRIVER_LOCATION_BATCH_RPC = "persist_driver_location_batch";

/**
 * بادئةُ مفاتيحِ المسارِ الساخنِ في Redis — منفصلةٌ عن بادئةِ الجلساتِ وعن دلوِ
 * الحدِّ وعن بثِّ التتبُّعِ، فلا يُمحى مسارٌ بمسحِ آخرَ.
 */
export const HOT_LOCATION_PREFIX = "waslah:driver-location";

/** مفتاحُ الحالةِ الساخنةِ لسائقٍ واحدٍ: تجزيئةٌ (HASH) لا نصٌّ مُسلسَلٌ. */
export function hotLocationKey(prefix: string, cityId: string, driverId: string): string {
  return `${prefix}:hot:${cityId}:${driverId}`;
}

/**
 * مفتاحُ قائمةِ الانتظارِ لمدينةٍ واحدةٍ: مجموعةٌ مُرتَّبةٌ (ZSET) عضوُها معرّفُ
 * السائقِ ودرجتُها طابعُ أحدثِ إصلاحةٍ له. والعضوُ الواحدُ لسائقٍ واحدٍ عن قصدٍ:
 * سائقٌ يبثُّ عشرَ نبضاتٍ في الدورةِ يُفرَّغُ **صفّاً واحداً** بأحدثِ موضعٍ، وهوَ
 * التجميعُ الذي وُجِدَ البندُ لأجلِه.
 */
export function hotLocationBacklogKey(prefix: string, cityId: string): string {
  return `${prefix}:backlog:${cityId}`;
}
