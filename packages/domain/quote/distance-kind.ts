/**
 * الغرض: صنفُ المسافةِ ووسمُه — مسافةٌ بلا وسمٍ **ممنوعةٌ بالنوعِ** لا بالمراجعةِ
 *   (`ADR 0024`)، وسياسةُ تقريبِها للعرضِ في موضعٍ واحدٍ.
 * الحالة: منفَّذٌ فعليّاً — البند `F2-04` (نصفُه المشروعُ).
 * ينتمي إلى: packages/domain/quote
 * يُستخدم من: `packages/application/quote/quote-ride.ts` ·
 *   `apps/miniapp/src/surfaces/rider/quote/quote-view.ts` ·
 *   `scripts/check-quote-contract.ts`
 * يُتوقع أن يستخدمه لاحقاً: `F2-06` (الرحلةُ النشطةُ) تعرضُ مسافةً مقطوعةً؛
 *   وصنفُها حينَها `ROUTE` إن جاءَت من محرِّكٍ — فيُضافُ الصنفُ ههنا ولا يُخترَعُ
 *   وسمٌ ثانٍ في موضعٍ آخرَ.
 * ملاحظات مستقبلية: إذا استُضيفَ محرِّكُ توجيهٍ فعلاً فالمسافةُ الحقيقيّةُ تُضافُ
 *   صنفاً جديداً `ROUTE`، **ولا تُستبدَلُ** المستقيمةُ — لأنَّ سقوطَ المحرِّكِ يجبُ
 *   أن يُعيدَنا إلى مسافةٍ موسومةٍ لا إلى فراغٍ.
 *
 * ## لماذا الوسمُ جزءٌ من القيمةِ لا حقلٌ مجاورٌ
 *
 * قاسَ `ADR 0024` نسبةَ الالتفافِ (طريقٌ ÷ مستقيمٌ) على **خمسةَ عشرَ زوجاً
 * حقيقيّاً** في جدةَ ومكةَ: أدناها 1.124 وأقصاها **2.834**. فمسافةٌ مستقيمةٌ
 * تُعرَضُ بلا وسمٍ تُقرأُ «هذا طولُ طريقي»، وهيَ في أسوأِ زوجٍ مقيسٍ **أقلُّ من
 * الحقيقةِ بنحوِ 65٪**. ولو كانَ الوسمُ حقلاً مجاوراً اختياريّاً لَسقطَ في أوّلِ
 * تمريرٍ بينَ طبقتَينِ ولَما أنّبَ المُصرِّفُ أحداً.
 *
 * فالمسافةُ ههنا **لا تُمثَّلُ رقماً**، بل `TaggedDistance` — حقلانِ إلزاميّانِ.
 * ومن أرادَ الرقمَ وحدَه فليقرأْه من داخلِ القيمةِ صريحاً، فيُرى في المراجعةِ.
 *
 * ## ولماذا التقريبُ ههنا لا في الشاشةِ
 *
 * «7581.8 متراً» رقمٌ صادقٌ وغيرُ صالحٍ للعرضِ: دقّتُه العشريّةُ تُوهِمُ ضبطاً
 * لا تملكُه مسافةٌ مستقيمةٌ أصلاً. ولو تُرِكَ التقريبُ للشاشةِ لَاختلفَ بينَ
 * الشاشةِ والبوتِ والإيصالِ، ولَصارَ الحدُّ (متى نقولُ متراً ومتى كيلومتراً)
 * ثلاثةَ أحكامٍ متفرِّقةٍ. فهوَ حكمُ نطاقٍ واحدٌ، والشاشةُ تُنسِّقُ لا تُقرِّرُ.
 *
 * ## ما لا يفعلُه هذا الملفُّ عن قصدٍ
 *
 * لا يُحوِّلُ مسافةً إلى زمنٍ: لا معاملَ التفافٍ ولا سرعةَ ثابتةً (`ADR 0024`
 * يمنعُهما بقياسٍ). ولا يُصيغُ نصّاً: يُعيدُ مفتاحاً ووسائطَ، والنصُّ في
 * قواميسِ i18n (§9.11). ولا يعرفُ أجرةً: الأجرةُ محجوبةٌ بـ`ADR 0039`.
 */

/**
 * صنفُ المسافةِ. صنفٌ واحدٌ اليومَ — والاتّحادُ مكتوبٌ اتّحاداً لا حرفاً واحداً
 * كي تُجبِرَ إضافةُ `ROUTE` غداً كلَّ مستهلكٍ على الإفصاحِ عن تعامُلِه معَه.
 */
export type DistanceKind = "STRAIGHT_LINE";

/** مسافةٌ لا تُمرَّرُ إلّا وهيَ موسومةٌ. */
export interface TaggedDistance {
  readonly kind: DistanceKind;
  /** بالأمتارِ، غيرُ سالبٍ، عدديٌّ. */
  readonly meters: number;
}

/**
 * حدُّ التحوُّلِ من المترِ إلى الكيلومترِ في العرضِ.
 *
 * ألفُ مترٍ لا تسعُ مئةٍ ولا كيلومترٌ واحدٌ: الحدُّ عندَ الوحدةِ الطبيعيّةِ نفسِها
 * كي لا يُقرأَ «900 م» و«1.0 كم» في شاشتَينِ عن مسافتَينِ متجاورتَينِ.
 */
export const METERS_DISPLAY_CEILING = 1000;

/** تقريبُ المترِ إلى أقربِ مئةٍ: دقّةُ العرضِ لا تعلو على دقّةِ المقياسِ. */
export const METERS_DISPLAY_STEP = 100;

/** مفتاحُ عرضٍ ووسائطُه — لا نصَّ (§9.11). */
export interface DistanceDisplay {
  readonly key: "rider.quote.distanceMeters" | "rider.quote.distanceKilometers";
  readonly value: number;
  /** يُعرَضُ دائماً معَ القيمةِ: الوسمُ لا يُفصَلُ عنها في أيِّ طبقةٍ. */
  readonly kind: DistanceKind;
}

/** هل القيمةُ مسافةٌ صالحةٌ أصلاً: عددٌ منتهٍ غيرُ سالبٍ. */
export function isMeasurableMeters(meters: number): boolean {
  return Number.isFinite(meters) && meters >= 0;
}

/**
 * سياسةُ عرضِ المسافةِ.
 *
 * تُعيدُ `null` لما لا يُقاسُ بدلَ أن تُعيدَ صفراً: «صفرُ مترٍ» تُقرأُ «أنتَ
 * هناكَ»، وهوَ توكيدٌ لا تملكُه قيمةٌ غيرُ عدديّةٍ. وهذا عينُ ما فعلَه
 * `MIN_DISPLAY_MINUTES` في `packages/domain/eta`.
 */
export function describeDistance(distance: TaggedDistance): DistanceDisplay | null {
  if (!isMeasurableMeters(distance.meters)) return null;
  if (distance.meters < METERS_DISPLAY_CEILING) {
    const rounded = Math.round(distance.meters / METERS_DISPLAY_STEP) * METERS_DISPLAY_STEP;
    /**
     * الحدُّ يُفحَصُ **بعدَ** التقريبِ لا قبلَه وحدَه. وأوّلُ كتابةٍ فحصَته قبلَه
     * فقط، فكانَ 980 متراً يُقرَّبُ إلى ألفٍ ويُعرَضُ «1000 م» — وحدةٌ تُخالِفُ
     * الحدَّ الذي أعلنَه هذا الملفُّ نفسُه، ورقمٌ لا يُقرأُ في شاشةِ هاتفٍ. فإن
     * بلغَ التقريبُ الحدَّ سقطَ الأمرُ إلى فرعِ الكيلومترِ أدناه.
     */
    if (rounded < METERS_DISPLAY_CEILING) {
      return { key: "rider.quote.distanceMeters", value: rounded, kind: distance.kind };
    }
  }
  // كيلومترٌ بعشريٍّ واحدٍ: عشرةُ أمتارٍ أدقُّ ما تستحقُّه مسافةٌ مستقيمةٌ.
  const km = Math.round(distance.meters / 100) / 10;
  return { key: "rider.quote.distanceKilometers", value: km, kind: distance.kind };
}
