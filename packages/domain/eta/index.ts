/**
 * الغرض: سياسةُ زمنِ الوصول (ETA) — دالّةٌ نقيّةٌ تُحوّل جوابَ محرّك التوجيه إلى
 *   حُكمٍ يصلح للعرض، أو إلى امتناعٍ مُصنَّف.
 * الحالة: منفّذ فعلياً — المرحلة ١٥.
 * ينتمي إلى: packages/domain/eta
 * يُتوقع أن يستخدمه لاحقاً: packages/application/tracking/estimate-arrival.ts،
 *   وأيّ سطحٍ يعرض زمناً للراكب أو للمشغّل.
 * ملاحظات مستقبلية: مطابقةُ المسار (المرحلة ١٦) قد تُحسّن دقّةَ نقطة البداية،
 *   ولا تُغيّر هذه السياسة: مدخلُها يبقى مدّةَ توجيهٍ ومقدارَ إلصاق.
 *
 * ## الحدّ الذي لا يُتجاوَز في هذه المرحلة
 *
 * زمنُ الوصول **مدّةُ توجيهٍ وحدها**: لا حركةَ مرورٍ آنيّة، ولا تعلُّمٌ من رحلاتٍ
 * سابقة، ولا ذكاءٌ اصطناعيّ. وهذا قيدٌ مُعلَنٌ لا نقصٌ مؤقّت: كلُّ ما سبق يحتاج
 * مصدرَ بياناتٍ لا نملكه ولا نستطيع إثباتَ صحّته، وتقديرٌ لا يُمكن إثباتُه أسوأُ
 * من امتناعٍ صريح.
 *
 * ## ولماذا لا تقديرَ بديلٌ بالدقائق حين يسقط المحرّك
 *
 * لأنّه قِيس فلم ينجح. الخطُّ المستقيم (هافرساين) أقصرُ من الطريق دائماً، والسؤالُ
 * هل يُصلَح بمعاملٍ ثابت. وقِيست النسبةُ على محرّك OSRM حقيقيّ في ١٥ زوجاً من
 * مواضع جدّة ومكّة الفعليّة:
 *
 *   أدنى = 1.124 · وسيط = 1.425 · p90 = 2.097 · أعلى = 2.834 · متوسط = 1.535
 *
 * ولو قُدِّرت المسافة بالمتوسّط لكان **أسوأ تقليلٍ ‎−45.9%‎ وأسوأ تكبيرٍ ‎+36.6%‎**.
 * وتقليلٌ بهذا القدر في زمن وصولٍ يعني قولَ «إحدى عشرة دقيقة» عن عشرين — وهو
 * كذبٌ على راكبٍ ينتظر في الشارع، لا تقريبٌ مقبول.
 *
 * والسرعةُ الضمنيّة في نفس العيّنة تراوحت **27.3 – 80.6 كم/س** (وسيط 53.1). فلا
 * سرعةَ ثابتةً تصلح كذلك — وأبطأُ الأزواج كان أقصرَها (1.5 كم بسرعة 27.3 كم/س)،
 * لأنّ الرحلةَ الحضريّة القصيرة تُهيمن عليها الإشاراتُ والانعطافات. أي أنّ السرعةَ
 * الثابتة تُخطئ أشدَّ الخطأ في أكثرِ الرحلات شيوعاً.
 *
 * فالقرار: محرّكُ التوجيه أو لا رقم. والمسافةُ المستقيمة تبقى معروضةً كما هي
 * موسومةً `STRAIGHT_LINE` (المرحلة ١٢) — مسافةٌ موسومةٌ ليست زمناً مُختلَقاً.
 */

/**
 * سقفُ الإلصاق الذي بعده لا يُعتبر الجوابُ خاصّاً بالموضع المسؤول عنه.
 *
 * الرقمُ مشتقٌّ من قياسٍ لا من تقدير. قِيس مقدارُ الإلصاق لخمسةَ عشرَ موضعاً
 * حقيقيّاً يستخدمه الناس في جدّة ومكّة، فكان المدى **5.8 م – 513.2 م**؛ وأعلاه
 * مركزُ المطار (513.2 م) ثمّ موضعٌ في مكّة (227.3 م) ثمّ الجامعة (148.8 م) —
 * وكلُّها مواضعُ مشروعةٌ يُطلَب منها فعلاً.
 *
 * وقِيست في المقابل مواضعُ ليست على شبكةٍ أصلاً: إحداثيةٌ في البحر الأحمر ألصقها
 * المحرّك على بُعد **51 700 م**، وإحداثيةٌ في مصر على بُعد **2 500 م**.
 *
 * فالحدُّ ١٠٠٠ م يقع فوق كلّ موضعٍ مشروعٍ مقيسٍ بفارقٍ يقارب الضِّعف، ودون أصغرِ
 * موضعٍ زائفٍ مقيس. وهو **غير مُعاير خارج جدّة ومكّة** — خطرٌ مُسجَّل لا حقيقةٌ
 * عامّة، والرقم يُراجَع حين تُضاف مدنٌ بشبكةِ طرقٍ أفقر.
 *
 * ولاحِظ ما لا يحكم عليه هذا الحدّ: موضعٌ في وسط الصحراء ألصقه المحرّك على بُعد
 * ١٠٠ م من طريقٍ صحراويٍّ حقيقيّ وأعاد ١٨٨ دقيقة — وهو **جوابٌ صحيح**، بعيدٌ لا
 * زائف. فالسؤالُ هنا «أهذا الجوابُ عن الموضع الذي سألتُ عنه؟» لا «أهو قريب؟».
 */
export const MAX_SNAP_METERS = 1000;

/**
 * أدنى ما يُعرَض. صفرُ دقائقٍ يُقرأ «وصل»، وهو توكيدٌ لا تملكه سياسةٌ تحسب مسافةً:
 * سائقٌ على بُعد ثلاثين ثانيةً لم يصل بعد. فالتدوير إلى دقيقةٍ واحدةٍ حدٌّ أدنى لا
 * تجميل — والحقيقةُ الكاملة (الثواني) تبقى في `seconds` لمن يحتاجها.
 */
export const MIN_DISPLAY_MINUTES = 1;

/**
 * سقفٌ يُعتبر بعده الجوابُ غيرَ معقولٍ لرحلةٍ داخل مدينة.
 *
 * وهو حرسٌ ضدّ ما قيس فعلاً لا احتمالٌ نظريّ: إحداثيةٌ في مصر أعادت `Ok` و**١٣٧٣
 * دقيقة** بإلصاقٍ ٢.٥ كم — أي أنّ حدّ الإلصاق وحده لم يكن ليمنعها لو كان الإلصاق
 * أصغر. وعرضُ «٢٣ ساعة» لراكبٍ في جدّة ليس تقديراً بل دليلٌ على أنّ أحد الطرفين
 * ليس حيث يُظنّ. والامتناعُ أصدقُ من رقمٍ يُصدَّق.
 *
 * والرقمُ ثمانُ ساعات: أطولُ رحلةٍ معقولةٍ داخل المملكة بين مدينتين متجاورتين
 * تبقى دونه بفارقٍ واسع (جدّة ← مكّة قِيست ٦١.٦ دقيقة)، ولا يمنع حالةً مشروعة.
 */
export const MAX_PLAUSIBLE_SECONDS = 8 * 60 * 60;

/** ما يُعطيه محرّكُ التوجيه للسياسة. لا شكلَ مزوّدٍ بعينه هنا. */
export interface RoutingDuration {
  readonly durationSeconds: number;
  readonly distanceMeters: number;
  /**
   * بُعدُ طرفَي المسار عن الطريق. `null` = المحرّكُ لم يُخبر — وهي حالةٌ تُعامَل
   * معاملةَ الامتناع لا معاملةَ الصفر (يُنظر `RouteSnap` في packages/maps).
   */
  readonly snapMeters: { readonly origin: number; readonly destination: number } | null;
}

/** سببُ امتناع السياسة عن إعطاء رقم. كلٌّ منها قرارٌ مختلفٌ للمشغّل. */
export type EtaUnavailableReason =
  /** لا مزوّدَ توجيهٍ مضبوطٌ أصلاً (`ROUTING_PROVIDER=none`). قرارُ مشغّلٍ لا عطل. */
  | "NOT_CONFIGURED"
  /** المحرّكُ لا يعمل: مهلة، اتصالٌ مرفوض، 5xx. عطلٌ عابرٌ يستحقّ تنبيهاً. */
  | "PROVIDER_DOWN"
  /** المحرّكُ أجاب: لا طريق. جوابٌ صحيحٌ نهائيّ لا عطل. */
  | "NO_ROUTE"
  /** أحدُ الطرفين بعيدٌ عن أيّ طريقٍ يعرفه المحرّك — فالجوابُ ليس عنه. */
  | "OFF_ROAD"
  /** المحرّكُ لم يُخبر بمقدار الإلصاق، فلا سبيلَ إلى التحقّق من أنّ الجواب عن الموضع. */
  | "SNAP_UNKNOWN"
  /** مدّةٌ خارج المعقول لرحلةٍ داخل مدينة — دليلُ خطأ في الطرفين لا تقدير. */
  | "IMPLAUSIBLE"
  /** لا موقعَ للسائق بعد، أو لا مقصدَ محدَّد. نقصُ مدخلاتٍ لا عطلُ محرّك. */
  | "NO_INPUT";

/**
 * حُكمُ السياسة — اتحادٌ مُميَّز. لا `minutes: number | null` مع `available: boolean`،
 * لأنّ ذلك يسمح بقراءة الرقم بلا فحصٍ ثمّ `?? 0` — وصفرُ دقائقٍ يعني «وصل».
 */
export type EtaVerdict =
  | {
      readonly kind: "ROUTED";
      /** المدّةُ كما أعطاها المحرّك، بلا تدوير — لمن يحسب لا لمن يعرض. */
      readonly seconds: number;
      /** الدقائقُ للعرض: مُدوَّرةٌ إلى أقرب دقيقةٍ وبحدٍّ أدنى واحدة. */
      readonly minutes: number;
      readonly distanceMeters: number;
      /** المصدرُ مُعلَنٌ في الحُكم نفسه: من يعرض الرقم يعرف من أين جاء. */
      readonly source: "ROUTING";
    }
  | { readonly kind: "UNAVAILABLE"; readonly reason: EtaUnavailableReason };

/** ما يمنع أصلاً: لا مدخلات. يُستدعى قبل أيّ نداءِ شبكة. */
export function etaNoInput(): EtaVerdict {
  return { kind: "UNAVAILABLE", reason: "NO_INPUT" };
}

export function etaUnavailable(reason: EtaUnavailableReason): EtaVerdict {
  return { kind: "UNAVAILABLE", reason };
}

/**
 * السياسة: مدّةُ توجيهٍ ⇒ حُكم.
 *
 * الترتيبُ مقصود: يُفحص الإلصاقُ **قبل** المعقوليّة، لأنّ سببَ الامتناع يُقرأ
 * ويُبنى عليه قرارُ مشغّل. فمسارٌ إلى البحر بإلصاقِ ٥١ كم سببُه `OFF_ROAD`
 * (إحداثيةٌ خاطئة)، لا `IMPLAUSIBLE` (خللٌ في المحرّك) — والفرقُ بينهما هو الفرقُ
 * بين «راجِع الموقع» و«راجِع الخادم».
 */
export function estimateEta(input: RoutingDuration): EtaVerdict {
  const { durationSeconds, distanceMeters, snapMeters } = input;

  // `Number.isFinite` لا `> 0` وحده: `NaN` و`Infinity` يمرّان من كلّ مقارنةٍ
  // بصمتٍ، ومدّةٌ `NaN` مُدوَّرةٌ تصير `NaN` دقيقةً تُعرَض نصّاً للراكب.
  if (!Number.isFinite(durationSeconds) || !Number.isFinite(distanceMeters)) {
    return etaUnavailable("PROVIDER_DOWN");
  }
  if (durationSeconds < 0 || distanceMeters < 0) {
    return etaUnavailable("PROVIDER_DOWN");
  }

  if (snapMeters === null) {
    return etaUnavailable("SNAP_UNKNOWN");
  }
  if (!Number.isFinite(snapMeters.origin) || !Number.isFinite(snapMeters.destination)) {
    return etaUnavailable("SNAP_UNKNOWN");
  }
  if (snapMeters.origin > MAX_SNAP_METERS || snapMeters.destination > MAX_SNAP_METERS) {
    return etaUnavailable("OFF_ROAD");
  }

  if (durationSeconds > MAX_PLAUSIBLE_SECONDS) {
    return etaUnavailable("IMPLAUSIBLE");
  }

  return {
    kind: "ROUTED",
    seconds: durationSeconds,
    minutes: Math.max(MIN_DISPLAY_MINUTES, Math.round(durationSeconds / 60)),
    distanceMeters,
    source: "ROUTING",
  };
}
