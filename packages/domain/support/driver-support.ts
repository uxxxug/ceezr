/**
 * الغرض: مجالُ دعمِ السائقِ — **أصنافُ شكواهُ** وما يلزمُها من رحلةٍ، وصفحةُ
 *   تذاكرِه (`F3-08` · `SD-10` · §9.11).
 * الحالة: منفَّذٌ فعليّاً — البند `F3-08`.
 * ينتمي إلى: packages/domain/support
 * يُستخدم من: `packages/application/support/driver-support.ts` ·
 *   `packages/infrastructure/support/driver-support-store.ts`
 * يُتوقع أن يستخدمه لاحقاً: لوحُ موظّفِ الدعمِ إن قرأَ أصنافَ السائقِ.
 * الحاكم: docs/adr/0114-a-support-ticket-is-a-spoken-reference-not-a-uuid.md
 *
 * ## لِمَ ملفٌّ ثانٍ ولا سطرٌ في أصنافِ الراكبِ
 *
 * نصُّ `SD-10`: «نفسُ `SR-11` **بأصنافِ السائقِ**». فالأصنافُ مختلفةٌ والمنطقُ
 * واحدٌ. ولو جُمِعَت في مصفوفةٍ واحدةٍ لَصارَ على كلِّ نداءٍ سؤالٌ «أيُّ قيمةٍ
 * منها لدورِ هذا الطالبِ؟» — وذاكَ حكمٌ يُنسى في مسارٍ. **فمجالُ كلِّ دورٍ مغلقٌ
 * على قيمِه**، والقاعدةُ تحكمُ خلفَه بـ`NOT_A_DRIVER` (بابانِ لا بابٌ).
 *
 * **ومجالُ القراءةِ لا يُقسَمُ**: هوَ في `ticket-types.ts` بعِلّتِه المكتوبةِ
 * هناكَ (صفٌّ واحدٌ يحملُ المعرِّفَينِ لحسابٍ ذي دورَينِ).
 *
 * ## ولِمَ «راكبٌ مسيءٌ» يلزمُها رحلةٌ و«خصمٌ» لا يلزمُها
 *
 * شكوى عن سلوكِ راكبٍ **بلا رحلةٍ لا موضوعَ لها**: لا يُعرَفُ عن أيِّ راكبٍ
 * يتحدَّثُ، ولا يُفتَّشُ شيءٌ — وهذا نظيرُ `driver_conduct` عندَ الراكبِ حرفاً.
 * **والخصمُ ليسَ كذلكَ**: قد يكونُ عن اشتراكٍ أو عن مجموعِ أسبوعٍ لا عن رحلةٍ
 * بعينِها، فإلزامُه برحلةٍ يمنعُ شكوى مشروعةً. **والمركبةُ** شأنُ وثيقةٍ أو
 * حالةٍ لا رحلةٍ. **والاشتراكُ** كذلكَ — وهوَ الصنفُ القائمُ منذُ المرحلةِ ٢٫٤
 * ولم يكن يلزمُه طلبٌ، **ولا يُغيَّرُ حكمُه الآنَ** (`ح-8`).
 *
 * ## وما لا يفعلُه هذا الملفُّ عن قصدٍ
 *
 *   ــ **لا يُولِّدُ مرجعاً**: التوليدُ تسلسلٌ في القاعدةِ (`ADR 0114`).
 *   ــ **لا يقولُ زمنَ الاستجابةِ**: إعدادٌ لكلِّ مدينةٍ (القاعدة 0.3).
 *   ــ **لا يمسُّ أصنافَ الراكبِ ولا صفحتَه**: يُقرأُ منها ما هوَ عديمُ الدورِ
 *      (الحالاتُ · المؤشِّرُ · حدودُ الصفحةِ) ولا يُنسَخُ ولا يُبدَّلُ (`ح-8`).
 *   ــ **لا يفتحُ بابَ إرفاقٍ**: دَينٌ مُعلَنٌ منذُ `F2-12` ولم يُبنَ.
 */

import type { SupportTicketCursor, SupportTicketStatus } from "./rider-support.ts";

/**
 * أصنافُ شكوى السائقِ — **مجالٌ مغلقٌ** يُقابِلُ قيمَ السائقِ في
 * `support_ticket_type` حرفاً، وهيَ الأربعُ المنصوصةُ في `SD-10`:
 * «خصمٌ، اشتراكٌ، راكبٌ مسيءٌ، مركبةٌ».
 */
export const DRIVER_SUPPORT_CATEGORIES = [
  /** اشتراكٌ — قائمٌ في القاعدةِ منذُ المرحلةِ ٢٫٤، ويُعرَضُ الآنَ في شاشتِه. */
  "subscription",
  /** خصمٌ — اعتراضٌ على مبلغٍ خُصِمَ. */
  "deduction",
  /** راكبٌ مسيءٌ — يلزمُها رحلةٌ. */
  "rider_conduct",
  /** مركبةٌ — وثيقةٌ أو فحصٌ أو حالةٌ. */
  "vehicle",
  /** عطبُ تطبيقٍ — للدورَينِ، ولا يُحجَبُ عن السائقِ. */
  "app_problem",
  /** أخرى — بابٌ لا يُغلَقُ على مَن لا يجدُ صنفَه. */
  "other",
] as const;

export type DriverSupportCategory = (typeof DRIVER_SUPPORT_CATEGORIES)[number];

export function isDriverSupportCategory(value: unknown): value is DriverSupportCategory {
  return (
    typeof value === "string" && (DRIVER_SUPPORT_CATEGORIES as readonly string[]).includes(value)
  );
}

/**
 * الأصنافُ التي **يجبُ** أن تتعلَّقَ برحلةٍ بعينِها — واحدٌ لا أكثرُ، بعِلّتِه
 * المكتوبةِ في رأسِ الملفِّ. **والقاعدةُ تفحصُ المِلكيّةَ** إن أُرسِلَ معرّفٌ؛
 * وهذا يفحصُ **الحضورَ**، وهما شرطانِ لا شرطٌ مُكرَّرٌ.
 */
export const DRIVER_CATEGORIES_REQUIRING_ORDER: readonly DriverSupportCategory[] = [
  "rider_conduct",
];

export function driverCategoryRequiresOrder(category: DriverSupportCategory): boolean {
  return DRIVER_CATEGORIES_REQUIRING_ORDER.includes(category);
}

export type { SupportTicketCursor, SupportTicketStatus };
