/** الوسيطُ الأوّلُ لـ`translate` كما يُطابِقُه الحاجزُ. */
export function foldingFrom(): string {
  return SEARCH_FOLDING.map(([from]) => from).join("");
}

/** والوسيطُ الثاني: يقصُرُ عن الأوّلِ بعددِ المحذوفاتِ — وذاكَ هوَ الحذفُ. */
export function foldingTo(): string {
  return SEARCH_FOLDING.map(([, to]) => to).join("");
}

/**
 * صنفُ المحارفِ الباقيةِ: أرقامٌ ولاتينيٌّ صغيرٌ وحرفٌ عربيٌّ (`ء`…`غ` و`ف`…`ي`
 * — والفجوةُ بينَهما مواضعُ التشكيلِ المحذوفِ سلفاً). وما سواه **يصيرُ فاصلاً**
 * لا يُحذَفُ: حذفُ الشَّرطةِ في «جدة-المدينة» يُلصِقُ كلمتَينِ فتُطابَقُ كلمةٌ
 * لا وجودَ لها؛ وجعلُها فراغاً يُبقي الحدَّ بينَهما.
 *
 * ونصُّه ههنا **هوَ عينُ نصِّه** في `regexp_replace` في الهجرةِ، يفرضُ التطابقَ
 * `scripts/check-destination-contract.ts` حرفاً — ولذا لا يُكتَبُ مختصراً هنا
 * ومشروحاً هناك.
 */
export const ALLOWED_CHARACTER_CLASS = "[^0-9a-z\\u0621-\\u063A\\u0641-\\u064A]+";

const FOLDING_MAP: ReadonlyMap<string, string> = new Map(SEARCH_FOLDING);

/**
 * التطبيعُ: طيٌّ، ثمَّ تصغيرٌ، ثمَّ كلُّ ما ليسَ مسموحاً فراغٌ، ثمَّ طيُّ
 * الفراغاتِ، ثمَّ قصُّ الطرفَينِ. الترتيبُ عينُ ترتيبِ الهجرةِ — ولو قُدِّمَ
 * التصغيرُ على الطيِّ لَمَا تغيّرَ شيءٌ (لا حالةَ للعربيِّ)، ويبقى الترتيبُ
 * واحداً كي يكونَ التطابقُ مقروءاً لا مُستنتَجاً.
 */
export function normalizeSearchText(input: string): string {
  let folded = "";
  for (const character of input) {
    const mapped = FOLDING_MAP.get(character);
    folded += mapped === undefined ? character : mapped;
  }
  return folded
    .toLowerCase()
    .replace(new RegExp(ALLOWED_CHARACTER_CLASS, "gu"), " ")
    .replace(/ +/gu, " ")
    .trim();
}

/**
 * مطابقةُ بدايةِ كلمةٍ — الرتبةُ الأولى في ترتيبِ النتائجِ. تعملُ على نصَّينِ
 * **مُطبَّعَينِ سلفاً**: الفراغُ الواحدُ فاصلُ الكلماتِ بعدَ التطبيعِ، فلا يُعادُ
 * ههنا. وعلّةُ وجودِها أنَّ مفتاحَ البحثِ يحملُ الاسمَ العربيَّ ثمَّ اللاتينيَّ في
 * نصٍّ واحدٍ: فمَن كتبَ `king` لا يُطابِقُ بدايةَ الحقلِ أبداً، ولو حُكِمَ ببدايةِ
 * الحقلِ وحدَها لَعاقبَتِ الرتبةُ لغةَ الكاتبِ.
 */
export function wordStartMatch(haystack: string, needle: string): boolean {
  if (needle.length === 0) return false;
  return haystack.startsWith(needle) || haystack.includes(` ${needle}`);
}

/**
 * حدُّ المدخلِ: محرفانِ على الأقلِّ. والحرفُ الواحدُ في العربيّةِ يُطابِقُ نصفَ
 * الدليلِ فيُعيدُ ضجيجاً لا نتيجةً؛ ولذا يُردُّ **ولا يُنادى الخادمُ** به.
 */
export const MIN_SEARCH_QUERY_LENGTH = 2;

/** والسقفُ حدُّ نقلٍ لا قيمةُ منتَجٍ (القاعدة 0.3): لا اسمَ معلَمٍ يبلغُه. */
export const MAX_SEARCH_QUERY_LENGTH = 80;

/**
 * الاستفهامُ المقبولُ: نصٌّ مُطبَّعٌ طولُه بينَ الحدَّينِ، أو `null`. والقياسُ
 * **بعدَ التطبيعِ** لا قبلَه: «  ـًـ  » ثلاثةَ عشرَ محرفاً خامّاً وصفرٌ مُطبَّعاً،
 * وقبولُه يُرسِلُ إلى القاعدةِ بحثاً يُطابِقُ الجدولَ كلَّه.
 */
export function readSearchQuery(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  if ([...raw].length > MAX_SEARCH_QUERY_LENGTH) return null;
  const normalized = normalizeSearchText(raw);
  if ([...normalized].length < MIN_SEARCH_QUERY_LENGTH) return null;
  return normalized;
}

