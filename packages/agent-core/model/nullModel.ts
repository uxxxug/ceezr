/**
 * الغرض: التنفيذ الوحيد لعقد النموذج اليوم — يُعيد «لا نموذج» دائماً.
 * الحالة: منفّذ فعلياً وهو **المقصود نهائياً في هذه المرحلة** — القسم 3، ب.7.
 * ينتمي إلى: packages/agent-core/model
 * يُتوقع أن يستخدمه لاحقاً: core.ts (يمرّره للوكيل)، وكل اختبار
 * ملاحظات مستقبلية: يبقى هذا الملف **حتى بعد وصل مزوّد حقيقي**، لأنه المزدوج
 *   الذي تعمل به الاختبارات بلا شبكة ولا كلفة ولا لاحتمية.
 *
 * ═══ لماذا نموذجٌ لا يفعل شيئاً بدل ألّا يكون هناك نموذج ═══
 *
 * لأن البديل أن يحمل كل مستدعٍ فرعاً شرطياً `if (model)`. عندها يصير وصل مزوّدٍ
 * حقيقياً يوماً ما تعديلاً في كل موضع، ويصير كل موضع احتمالَ سهو. مع هذا الملف
 * الوكيل يسأل النموذج دائماً، ويتعامل مع `available: false` دائماً — **فالمسار
 * الذي سيُختبَر يوم يوجد مزوّد هو المسار الذي يعمل اليوم**، لا مسارٌ نائم لم
 * يمرّ عليه أحد.
 *
 * وهذا يعني أن وكيل الدعم **لا يعتمد على نموذج إطلاقاً**: تصنيفه بمطابقة كلمات،
 * واقتراحه من `knowledge_base/`. النموذج إضافةٌ لا أساس، ولذلك عمل الوكيل كاملٌ
 * وهو معطَّل.
 */

import type { ModelAdapter, ModelRequest, ModelResponse } from "../schemas.ts";
import { unavailableResponse } from "./modelAdapter.ts";

export const NULL_MODEL_NAME = "null-model";

/**
 * يُعيد `available: false` فوراً. **لا شبكة، لا مفتاح، لا كلفة، لا انتظار.**
 * `async` رغم أنه متزامن: التوقيع هو نفسه يوم يُستبدل بمزوّد حقيقي، فلا يتغيّر
 * حرفٌ عند من يستدعيه.
 */
export function createNullModel(): ModelAdapter {
  return {
    name: NULL_MODEL_NAME,
    complete: async (_request: ModelRequest): Promise<ModelResponse> => unavailableResponse(0),
  };
}

/** المزدوج الجاهز — يُستورَد مباشرةً حيث لا حاجة لنسخة مستقلّة. */
export const nullModel: ModelAdapter = createNullModel();
