-- ## لماذا `is_active = false` رغم أن المطلوب «تفعيلها»
--
-- القيد `cities_active_requires_groups` يمنع تفعيل مدينةٍ قبل ربط قروباتها
-- الثلاثة، وهو قيدٌ صائب: مدينةٌ مفعَّلة بلا قروب إسناد تقبل الطلبات ثم تبتلعها
-- بلا مسار تصعيد — وهذا بعينه ما شكا منه المالك في المدن الأخرى.
--
-- ومعرّفات القروبات لا تُخترع: هي أرقام قروبات تلغرام حقيقية يُنشئها المالك
-- ويُضيف إليها البوتين. فلو كتبتُ أرقاماً من عندي لفعّلتُ مدينةً تُرسل إلى
-- العدم. فالبذرة هنا تُنشئ المدينة وإعداداتها كاملة، والتفعيل خطوةٌ واحدة
-- تُنفَّذ متى توفّرت الأرقام — وهي مكتوبة في الأسفل جاهزةً للنسخ.
--
-- ## لماذا الإعدادات تُنسخ من مدينة قائمة لا تُكتب يدوياً
--
-- البند 0.4 يفرض `city_id` على كل صفّ في `platform_settings`. فمدينةٌ بلا
-- إعدادات ستقرأ أصفاراً أو تفشل عند أول مطابقة. والنسخ من مدينة قائمة يضمن
-- أن أي مفتاح أُضيف بعد البذرة الأولى ينتقل معه، فلا تتخلّف المدينة الجديدة
-- عن أخواتها كلّما أُضيف مفتاح.
