-- الغرض: الفريدُ الجزئيُّ: منزلٌ واحدٌ وعملٌ واحدٌ لكلِّ مستخدمٍ — البند `F2-02` (SR-02).
-- الحالة: مُطبَّقةٌ بالمُطبِّقِ الآمنِ في طورِ `index` بلا معاملةٍ.
-- ينتمي إلى: supabase/migrations
-- يُستخدم من: `upsert_saved_place` — عبارةُ `on conflict (user_id, kind) where kind in ('home','work')` تستندُ إلى هذا الفهرسِ بعينِه.
-- ما لا تفعله: لا تُغيِّرُ مخطّطاً ولا بيانةً ولا تحجبُ الكتابةَ (`concurrently`).
--
-- ## العودة (rollback)
--
-- `drop index concurrently if exists saved_places_user_singleton_idx;` — ولا تُفقَدُ بيانةٌ. **لكنَّ العودةَ تُبطِلُ `on conflict` في الدالّةِ فتُخفِقُ الكتابةُ — فيجبُ أن تسبقَها عودةُ الهجرةِ `20260913050000`، لا أن تُفرَدَ عنها.** و`other` خارجَ الشرطِ عن قصدٍ: قائمةٌ مفتوحةٌ (`SR-12`)، ولو شملَه الفريدُ لَمَنَعَ المكانَ الثانيَ.
--
-- ## ولماذا ملفٌّ لكلِّ فهرسٍ
--
-- `create index concurrently` لا تُقبَلُ داخلَ معاملةٍ، والمُطبِّقُ الآمنُ يُرسِلُ
-- الملفَّ متعدِّدَ العباراتِ في معاملةٍ واحدةٍ — فملفٌّ لكلِّ فهرسٍ شرطُ تنفيذٍ لا
-- ذوقُ تنظيمٍ، وحاجزُ `scripts/check-migration-safety.ts` يفرضُه.
-- =============================================================================

create unique index concurrently if not exists saved_places_user_singleton_idx
  on saved_places (user_id, kind)
  where kind in ('home', 'work');
