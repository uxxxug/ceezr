insert into cities (code, name_ar, name_en, is_active)
values
  ('MKK', 'مكة',    'Makkah', false),
  ('RUH', 'الرياض', 'Riyadh', false),
  ('TIF', 'الطائف', 'Taif',   false)
on conflict (code) do nothing;

-- الإعدادات: تُنسخ من جدة كمرجع لكل مدينة جديدة، ويُتجاهل ما هو موجود سلفاً
-- حتى تكون هذه الهجرة قابلة لإعادة التشغيل بلا أثر جانبي.
insert into platform_settings (city_id, key, value, value_type, description_ar, is_provisional)
select
  c.id,
  src.key,
  src.value,
  src.value_type,
  src.description_ar,
  src.is_provisional
from cities c
cross join lateral (
  select ps.key, ps.value, ps.value_type, ps.description_ar, ps.is_provisional
  from platform_settings ps
  join cities ref on ref.id = ps.city_id
  where ref.code = 'JED'
) src
where c.code in ('MKK', 'RUH', 'TIF')
on conflict (city_id, key) do nothing;

