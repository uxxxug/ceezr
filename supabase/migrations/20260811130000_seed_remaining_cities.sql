--   كبقيّة المدن، جاهزة للتفعيل فور توفّر معرّفات قروباتها الثلاثة.
-- الحالة: منفّذ فعلياً — البند: تفعيل باقي المدن.
-- ينتمي إلى: supabase/migrations
--
-- ## لماذا `is_active = false`
--
-- القيد `cities_active_requires_groups` يمنع تفعيل مدينةٍ قبل ربط قروباتها
-- الثلاثة. ومعرّفات القروبات أرقامٌ حقيقية يُنشئها المالك في تلغرام ويُضيف
-- إليها بوت السائق. فكتابة أرقامٍ من عندنا تُفعّل مدينةً تُرسل إلى العدم.
-- البذرة هنا تُنشئ المدينة وإعداداتها كاملة، والتفعيل خطوةٌ واحدة تُنفَّذ
-- متى توفّرت الأرقام — عبر `admin_update_city_group_ids` أو مسار اللوحة
-- `POST /admin/settings/:cityId/group-ids` (لا UPDATE خام).
--
-- ## لماذا الإعدادات تُنسخ من جدة
--
-- البند 0.4 يفرض `city_id` على كل صفّ في `platform_settings`. ومدينةٌ بلا
-- إعدادات تقرأ أصفاراً أو تفشل عند أول مطابقة. والنسخ من مدينة قائمة يضمن
-- انتقال أي مفتاح أُضيف بعد البذرة الأولى، فلا تتخلّف المدينة الجديدة عن
-- أخواتها. والإعدادات منسوخة حرفياً من جدة فهي بحاجة لمراجعة تسعير مستقلّة
-- لاحقاً لكل مدينة على حدة.
