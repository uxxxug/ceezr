-- ## العودة (rollback)
--
-- `drop index concurrently if exists city_service_areas_active_city_idx;` — بلا فقدِ بيانةٍ. ولا تُبطِلُ دالّةً: `resolve_destination` تقرأُ بـ`order by created_at desc limit 1` لا بـ`on conflict`، فالعودةُ تُفقِدُ **المنعَ** لا القراءةَ.
