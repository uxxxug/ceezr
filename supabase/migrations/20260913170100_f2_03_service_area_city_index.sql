-- الحدُّ القديمُ يبقى صفّاً مُعطَّلاً كي يُقرأَ لماذا قُبِلَت وجهةٌ بالأمسِ ورُفِضَت اليومَ. ولو كانَ الفريدُ على `city_id` كلِّه لَاستلزمَ كلُّ تحديثٍ حذفَ التاريخِ — وذاكَ محوُ دليلٍ لا تنظيمُ جدولٍ.
