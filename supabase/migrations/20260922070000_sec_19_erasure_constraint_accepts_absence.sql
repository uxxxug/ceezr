   لـ`ADR 0175`) أو سالبٌ (المسلكُ التراثيُّ/الانتقاليُّ للصفوفِ القائمةِ قبلَ
   إسقاطِ `not null`). التقويةُ **إفصاحٌ لا إصلاحٌ**: السلوكُ لم يتغيّرْ، قِيسَ
