-- SEC-19 — بندُ الترتيبِ ٢: تقويةُ قيدِ التجهيلِ ليقبلَ الغيابَ صراحةً
--   (إفصاحٌ لا إصلاحٌ)
--
--   **السياقُ:** قيدُ `users_erased_rows_carry_no_identity` (من هجرة
--   `20260914180000`) منشورٌ بنصٍّ يقولُ `telegram_id < 0` — أي «سالبٌ» — لكنَّ
--   سلوكَه على PostgreSQL يَقبَلُ `telegram_id is null` بحكمِ المجهولِ
--   الثلاثيِّ (`null < 0` مجهولٌ، و`check` يَقبَلُ المجهولَ). قِيسَ ذلك في
--   `tests/integration/erasure-check-against-absent-identity.test.ts`: المُسنَدُ
--   المنشورُ والمُسنَدُ المُقوَّى تساوَيا في الحالاتِ السّتِّ كلِّها — **فلا
--   ثقبَ أمانٍ**.
--
--   **ما تُغيِّرُه هذه الهجرةُ:** نصَّ القيدِ وحدَه. تُسقِطُ القيدَ وتُعيدُ
--   إنشاءَه بمُسنَدٍ يذكرُ الفرعَ صراحةً: `telegram_id is null or
--   telegram_id < 0`. فلا يعودُ القارئُ يستنتجُ أنَّ الغيابَ مرفوضٌ.
--
--   **ما لا تُغيِّرُه:** `users.telegram_id` يبقى `bigint not null` — إسقاطُ
--   القيدِ بندٌ ٤ من الترتيبِ المُلزِمِ، ولم يأتِ. والسلوكُ لا يتغيّرُ.
--
--   **القرارُ:** `ADR 0175` — `null` هوَ التمثيلُ المستقبليُّ للهويّةِ المنقولةِ
--   بعدَ التجهيل، والمُعرِّفُ السالبُ مسلكٌ تراثيٌّ/انتقاليٌّ للصفوفِ القائمةِ.
--   `erase_my_account` لا يُمَسُّ (يبقى يُسُكُّ سالباً) — تغييرُه بندٌ ٤.
--
--   **الطورُ:** `contract` — الإسقاطُ وإعادةُ الإنشاءِ عمليّةٌ تقليصيّةٌ (تُغيِّرُ
--   نصَّ قيدٍ قائمٍ)، فمحلُّها طورُ `contract` وحدَه. والقيدُ يُضافُ `not valid`
--   لئلّا يُمسحَ الجدولُ كلُّه تحتَ قفلٍ حاجزٍ، ويُصادَقُ في طورِ `validate`
--   بهجرةٍ تاليةٍ بقفلٍ أخفَّ. والمُسنَدُ الجديدُ أوسعُ من القديمِ (يَقبَلُ
--   كلَّ ما يَقبَلُه القديمُ وزيادةً)، فلا صفٌّ قائمٌ يَنقُضُه — لكنَّ القاعدةَ
--   آمرةٌ بلا استثناءٍ.
--
--   **التراجعُ:** القيدُ يُعادُ إلى نصّه الأوّلِ بإعادةِ هجرةِ
--   `20260914180000` الأصليةِ. لا أثرَ تخريبيٌّ: لا حذفَ عمودٍ ولا دالّةٍ ولا
--   سياساتٍ.
-- =============================================================================

-- PostgreSQL لا يُقدِّمُ `alter constraint ... check (...)`؛ الإسقاطُ ثمَّ
-- الإعادةُ هما الطريقُ الوحيدُ لتغييرِ نصِّ القيد.
alter table users drop constraint if exists users_erased_rows_carry_no_identity;

-- `not valid`: لا تُمسحُ البياناتُ القائمةُ تحتَ قفلٍ حاجزٍ. القيدُ يُفرَضُ على
-- الكتاباتِ الجديدةِ فوراً، ويُصادَقُ على القديمةِ في طورِ `validate` التالي.
-- والمُسنَدُ أوسعُ من القديمِ، فلا صفٌّ قائمٌ يَنقُضُه — لكنَّ القاعدةَ آمرةٌ.
alter table users add constraint users_erased_rows_carry_no_identity
  check (
    erased_at is null
    or (full_name is null and phone is null and telegram_username is null
        and (telegram_id is null or telegram_id < 0))
  ) not valid;

