-- ## الجذرُ المُثبَتُ (EXPLAIN محليٌّ على PostgreSQL 18.4 مع كلِّ الهجراتِ)

-- استعلامُ الترشيحِ يرشِّحُ المتاحينَ (`a.is_available = true`) ثم يرتبُهم
-- بالمسافةِ KNN (`order by d.last_location <-> point`) وحدَّهُ ٥٠. والمخطِّطُ
-- يبدأُ من فهرسِ GiST فيمشي على **كلِّ سائقي الصندوقِ** بالترتيبِ ويفحصُ
-- توافرَ كلِّ واحدٍ — فلا يستطيعُ التوقفَ المبكرَ إن كانَ المتاحونَ قليلينَ،
-- والكلفةُ تصيرُ O(كلِّ السائقينَ) لا O(المتاحينَ). وفي الموجةِ ينمو
-- المشروعُ سائقًا لكلِّ رحلةٍ (٣٦ ألفًا) وغالبيتُهم غيرُ متاحينَ — فنما زمنُ
-- الطورِ خطِّيًّا من ٣ ملّي إلى ٥٧–٨٧ ملّي. وبالفهرسِ الجزئيِّ يقلبُ
-- المخطِّطُ الانطلاقَ: يمسحُ فهرسَ المتاحينَ وحدهُ (٣٠ صفًّا في التجربةِ)
-- ثم يفرزُهم — والزمنُ ثابتٌ مهما نما الجدولُ (١٫٢ ملّي عندَ ٧٢٠٠ سائقًا).

-- ## ما لا تفعله

-- لا يُغيِّرُ مخططًا ولا بيانةً ولا استعلامًا ولا يحجبُ الكتابةَ
