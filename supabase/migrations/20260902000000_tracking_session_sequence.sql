-- ## لماذا عمودٌ في صفِّ الجلسةِ لا تسلسلٌ عامٌّ (`sequence`) ولا عدّادٌ في العمليةِ
--
-- `ADR 0053` §٣-أ/٢ و§٣-أ/٣ يُثبِّتان أنَّ نطاقَ الترتيبِ **جلسةُ التتبُّعِ الواحدةُ**،
-- وأنَّه **لا ترتيبَ كلّيَّ** بين الجلساتِ. وكائنُ `sequence` في PostgreSQL عدّادٌ
-- عالميٌّ بطبعِه، فاستعمالُه كان سيُنشئ ترتيباً كلّيّاً لم يُطلَب ولا يُمكن للعميلِ
-- أن يقيسَ به فجوةً على قناتِه: القفزُ من ٧ إلى ٩٣ في مجرًى واحدٍ يبدو فجوةً وهو
-- مجرَّدُ أرقامٍ استهلكها سائقٌ آخرُ.
--
-- والعمودُ في الصفِّ يُحقِّق ما لا يُحقِّقه عدّادُ ذاكرةٍ (§٣-أ/٤ و٥): الرقمُ يبقى
-- صحيحاً بعدَ إعادةِ تشغيلِ الخادمِ لأنَّه ليس في العمليةِ أصلاً، ويُثبَّت في نفسِ
-- الكتابةِ الذرّيّةِ التي تُثبِّت تقدُّمَ الجلسةِ (§٣-أ/٦) — فلا نافذةَ بين توليدِ
-- الرقمِ وحفظِ الحالةِ التي يُمثِّلها.
--
-- ## لماذا `integer` لا `bigint`
--
-- سقفُ الجلسةِ الواحدةِ اثنتا عشرةَ ساعةً (`DEFAULT_SESSION_POLICY.maxSessionSeconds`)،
-- والعدّادُ يُستهلَك مرّةً لكلِّ إصلاحةٍ مقبولةٍ ومرّتَينِ لدورةِ الحياةِ (فتحٌ وإغلاقٌ).
-- فحتّى بعشرِ إصلاحاتٍ في الثانيةِ — وهو أضعافُ ما يُرسله تلغرام — لا تتجاوز الجلسةُ
-- نصفَ مليونٍ، وسقفُ `integer` ملياران. والعدّادُ **لا يتراكم عبرَ الجلساتِ** لأنَّ
-- نطاقَه الصفُّ لا السائقُ.
--
-- وللاختيارِ أثرٌ عمليٌّ لا تجميليٌّ: `postgres.js` يُعيد `int8` **نصّاً** لا رقماً
-- (حِفظاً لدقّةِ ما يتجاوز `Number.MAX_SAFE_INTEGER`)، فكان `bigint` سيُدخِل تحويلاً
-- يدويّاً في كلِّ موضعِ قراءةٍ — وأوّلُ موضعٍ يُنسى فيه التحويلُ يُنتج مقارنةَ نصٍّ
-- بنصٍّ تقول إنَّ `"10" < "9"`، أي تراجعاً في الترتيبِ من حيثُ أُريد منعُه.
--
-- ## لماذا يبدأ من ١ لا من ٠
--
-- `ADR 0053` §٤-أ: «رقمُ الفتحِ هو أوّلُ أرقامِ القناةِ». فالصفُّ يُولَد وقد استُهلك
-- أوّلُ رقمٍ في حدثِ `session_started`، ولا يوجد في القناةِ حدثٌ رقمُه صفرٌ.
-- والصفرُ محجوزٌ لمعنًى واحدٍ عندَ المستهلكِ: «لم أُطبِّق شيئاً بعدُ» (`lastAppliedSeq`
-- الابتدائيّةُ)، فلو حملَه حدثٌ حقيقيٌّ لالتبس الحدثُ بالفراغِ.
--
-- ## الصفوفُ القائمةُ والرجوعُ
--
-- الجلساتُ القائمةُ تأخذ ١ بحكمِ `default`. والجلسةُ المفتوحةُ منها تُكمِل من ١ فتُصدِر
-- ٢ لأوّلِ إصلاحةٍ بعدَ الهجرةِ؛ ولا يضرُّ ذلك مستهلكاً لأنَّه يُحاذي `lastAppliedSeq`
-- من اللقطةِ المرجعيّةِ لا من ذاكرةٍ سابقةٍ للنشرِ (§٣-أ/٩).
--
-- والرجوعُ عن هذه الهجرةِ سطرٌ واحدٌ — والمستودعُ لا يحفظ ملفَّات `down` (يُنظر
-- `supabase/migrations/README.md`: الهجراتُ تُطبَّق بترتيبِ أسمائِها، ولا آليّةَ عكسٍ
-- تلقائيّةٍ)، فيُكتَب هنا صريحاً لا يُترَك للاجتهادِ:
--
--     alter table tracking_sessions drop constraint if exists tracking_sessions_sequence_positive;
--     alter table tracking_sessions drop column if exists last_sequence;
--
-- وهو رجوعٌ آمنٌ: العمودُ لا يُقرأ من دالّةٍ ولا من فهرسٍ ولا من قيدٍ خارجيٍّ، وحذفُه
-- يُعيد السلوكَ إلى ما كان عليه قبلَ `BUG-009` بلا فقدِ صفٍّ واحدٍ.

alter table tracking_sessions
  add column if not exists last_sequence integer not null default 1;

alter table tracking_sessions
  drop constraint if exists tracking_sessions_sequence_positive;

-- القيدُ يحرس الحدَّ الأدنى لا الرتابةَ: الرتابةُ تُفرَض بصيغةِ الكتابةِ
-- (`last_sequence = last_sequence + 1` داخلَ `update` واحدةٍ)، ولا يُمكن التعبيرُ عنها
-- في `check` لأنَّها علاقةٌ بين حالتَينِ لا شرطٌ على حالةٍ واحدةٍ.
alter table tracking_sessions
  add constraint tracking_sessions_sequence_positive check (last_sequence >= 1);

comment on column tracking_sessions.last_sequence is
  'آخرُ رقمِ ترتيبٍ أصدرَه الخادمُ لهذه الجلسةِ. نطاقُه هذا الصفُّ وحدَه — لا ترتيبَ كلّيَّ بين الجلساتِ. يُزاد داخلَ نفسِ الكتابةِ الذرّيّةِ التي تُثبِّت تقدُّمَ الجلسةِ، ولا يُزاد لكتابةٍ مرفوضةٍ. ADR 0053.';
