-- ## لِمَ هجرةٌ لا تفعلُ إلّا ثلاثَ عباراتٍ
--
-- `alter type … add value` **لا تُقرأُ قيمتُه في المعاملةِ التي أضافَته** (قيدُ
-- PostgreSQL)، و`scripts/migrate.ts` يُطبِّقُ كلَّ ملفٍّ **في معاملةٍ واحدةٍ**.
-- فلو أضفنا القيمَ وحكمنا بها في ملفٍّ واحدٍ لَسقطَت الهجرةُ عندَ أوّلِ
-- `p_type = 'deduction'`. **فالفصلُ ههنا ليسَ ترتيباً جميلاً بل شرطُ صحّةٍ**:
-- هذا الملفُّ يُوسِّعُ النوعَ، والذي يليهِ (`…020000`) يحكمُ بهِ.
--
-- ## ولِمَ تُوسَّعُ الأصنافُ ولا يُزادُ عمودُ «صنفِ سائقٍ»
--
-- نصُّ `SD-10` حرفاً: «**نفسُ `SR-11`** بأصنافِ السائقِ». وعمودٌ ثانٍ بجوارِ
-- `type` مصدرُ حقيقةٍ مكرَّرٌ يُسألُ أيُّهما يَحكُمُ عندَ اختلافِهما، وكلُّ ما
-- يقرأُ `support_ticket_type` اليومَ — الدعمُ وبطاقةُ القروبِ ومُوجِّهُ
-- التذاكرِ — يلزمُه أن يقرأَ الثانيَ أيضاً. **فالنوعُ الواحدُ يبقى واحداً.**
--
-- ## والأصنافُ الأربعةُ في نصِّ البندِ ثلاثةٌ ههنا — ولماذا
--
-- `SD-10` يقولُ: «خصمٌ، **اشتراكٌ**، راكبٌ مسيءٌ، مركبةٌ». و`subscription`
-- **قائمٌ في النوعِ منذُ المرحلةِ ٢٫٤** وتردُّه القاعدةُ للراكبِ بـ`NOT_A_DRIVER`
-- منذُ ذلكَ الحينِ — فإضافتُه ثانياً عبثٌ. فالجديدُ ثلاثٌ لا أربعٌ، **والرابعُ
-- موجودٌ لا منقوصٌ** (`ح-8`: يُزادُ ولا يُكرَّرُ).
--
-- ## وما لا تفعلُه هذه الهجرةُ عن قصدٍ
--
--   ــ **لا تُنشئُ جدولاً** فلا سؤالَ عن `city_id` جديدٍ (القاعدة 0.4).
--   ــ **لا تمسُّ دالّةً**: ذاكَ الملفُّ التالي، وخلطُهما يُسقِطُ الاثنَينِ.
--   ــ **لا تمسُّ أصنافَ الراكبِ** ولا تُعيدُ تعريفَ قيمةٍ قائمةٍ (`ح-8`).
--   ــ **لا تحذفُ قيمةً**: حذفُ قيمةٍ من نوعٍ معدودٍ في PostgreSQL غيرُ ممكنٍ
--      أصلاً، وصفوفٌ قديمةٌ تحملُها — فالتوسيعُ طريقٌ واحدٌ لا رجعةَ فيهِ،
--      وذلكَ سببُ اقتصارِنا على ثلاثٍ منصوصةٍ في البندِ لا أكثرَ.
