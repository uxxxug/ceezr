-- ── أصنافُ السائقِ الثلاثةُ ───────────────────────────────────────────────
-- `if not exists` يجعلُ كلَّ عبارةٍ idempotent، فإعادةُ التطبيقِ بلا أثرٍ.

-- «خصمٌ» — اعتراضٌ على مبلغٍ خُصِمَ من حصيلتِه.
alter type support_ticket_type add value if not exists 'deduction';

-- «راكبٌ مسيءٌ» — نظيرُ `driver_conduct` من الجهةِ الأخرى، ولا يُعادُ استعمالُ
-- ذاكَ الاسمِ للطرفَينِ: تذكرةٌ عن سلوكٍ يجبُ أن تقولَ **سلوكَ مَن**.
alter type support_ticket_type add value if not exists 'rider_conduct';

-- «مركبةٌ» — عطبٌ أو بلاغٌ يتعلَّقُ بمركبتِه هوَ (وثيقةٌ، فحصٌ، حالةٌ).
alter type support_ticket_type add value if not exists 'vehicle';
