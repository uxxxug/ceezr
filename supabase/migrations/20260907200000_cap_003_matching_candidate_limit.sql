-- ============================================================================
-- CAP-003 — حدُّ نافذة المرشّحين: matching_candidate_limit
--
-- ## العطب المُقاس قبل هذه الهجرة
--
-- `findAvailableInCity` يحمّل كلّ سائقي المدينة إلى الذاكرة بفلترة `city_id` وحدَه،
-- ثمّ يترك للدومين `evaluateCandidates` أن يُرشِّحَ بالمسافة والتوفّر والتوثيق والخدمة
-- والاشتراك. وهذا يعمل بنتائج صحيحة، لكنّه يُحمّلُ صفوفاً لا تُقرأ: سائقٌ خارجُ
-- نصف القطر، أو محجوبٌ، أو غيرُ متاحٍ، أو غيرُ موثَّقٍ، يُجلبُ ويُحوَّل ويُفحصُ
-- ثمّ يُرفَض. ومع نموّ السائقين تصيرُ القراءةُ هي العنق لا المطابقة.
--
-- وفهرس GiST (`drivers_location_gix`) موجودٌ منذ المرحلة 2.1 لكنّه لا يُستخدم:
-- الاستعلام الحالي بلا `ST_DWithin` فيُمسحُ الجدولُ كاملَه. وهذا تحديداً ما نصَّ عليه
-- البند CAP-003.
--
-- ## لماذا إعدادٌ للمدينة لا ثابتٌ في الكود
--
-- عددُ المرشّحين الذين يكفي فحصُهم قبل اختيار دفعة البثّ قرارٌ تشغيليٌّ يختلف
-- بالمدينة وبكثافة السائقين: مدينةٌ سائقوها كُثرٌ داخل نصف القطر يكفيها حدٌّ صغير،
-- ومدينةٌ سائقوها متفرّقون تحتاج نافذةً أوسع كي لا يفوتَ سائقٌ مؤهَّلٌ أبعدُ بسببَ
-- امتلاء النافذة بغير المؤهَّلين قبلَه. وترميزه في الكود يعني نشراً لكلّ ضبطٍ —
-- وهو ما تتجنّبه `platform_settings` في كلّ معامل مطابقةٍ آخر.
--
-- ## ولماذا يُبذَر ٥٠ لا قيمةً أصغر
--
-- حجمُ دفعة البثّ (`broadcast_batch_size`) مبذورٌ خمسة. ولو جُعل حدُّ النافذةِ مساوياً
-- له لخسرنا سائقين مؤهَّلين: حين يكونُ أقربُ خمسةٍ بلا الخدمة المطلوبة أو بلا
-- اشتراكٍ حيٍّ، يُختارُ غيرُهم أبعدُ منهم — لكنّهم خارجُ النافذة فلا يصلون أصلاً.
-- فالحدُّ يُتركُ أوسعَ من دفعة البثّ بقدرٍ يسمحُ للدومين بأن يفلترَ الخدمةَ
-- والاشتراكَ فوق نتيجةِ SQL دون أن يفقدَ مؤهَّلاً قريباً. والقيمةُ الافتراضيّةُ ٥٠
-- مُحايدةٌ بمعنى أنها لا تُفرِّغُ دفعةً في مدينةٍ صغيرة (خمسةُ سائقين كلُّهم داخلَ
-- النافذة) ولا تخنقُ مدينةً كبيرة (حيثُ يستطيع المشغّلُ رفعَها من لوحة الإدارة).
-- ولذلك `is_provisional = true`: قيمةٌ أوّليّةٌ تُعدَّلُ بالقياس لا بالتخمين.
--
-- ## ما الذي يبقى في الدومين
--
-- SQL يُضيّقُ النافذةَ بالبوابات الصلبة: المدينةُ، الحجبُ، التوثيقُ، التوفّرُ،
-- القربُ (`ST_DWithin`)، وعمرُ الموقعِ إن فُعّل. ويُرتّبُها بالمسافة ويحدُّها بـ`k`.
-- أمّا الخدمةُ والاشتراكُ فيُتركانِ للدومين: منطقُهما معتمدٌ على `now` وعلى خريطة
-- plan→service معقّدةٌ، وتكرارُهما في SQL خطرُ انحرافٍ صامتٍ. والدومينُ يحتفظُ
-- بـ`evaluateCandidates` حارساً نهائيّاً، وبـ`scoreCandidate` للترتيب بالـscore لا
-- بالمسافةِ وحدَها، وبـ`selectBroadcastBatch`. فإذا فرَّغتِ النافذةُ من المؤهَّلين
-- رجعَ `matchOrder` إلى `findAvailableInCity` كمسارٍ تشخيصيٍّ يبني قائمةَ الرفضِ
-- المُسبَّبة كاملةً — لا ليعيدَ تحميلَ كلّ السائقين في التشغيلِ الطبيعي، بل ليُجيبَ
-- عن سؤالِ «لماذا لا يصلُ أحدٌ؟» حين لا يصلُ أحدٌ.
-- ============================================================================

insert into platform_settings (city_id, key, value, value_type, description_ar, is_provisional)
select c.id,
       'matching_candidate_limit',
       '50'::jsonb,
       'number',
       'حدُّ نافذة المرشّحين القريبين التي يُرجعها استعلام PostGIS قبل ترتيب الدومين. أوسعُ من دفعة البثّ كي لا يفوتَ مؤهَّلٌ أبعدُ بسببَ امتلاء النافذة بغير المؤهَّلين قبله',
       true
  from cities c
 where not exists (
   select 1 from platform_settings s
    where s.city_id = c.id and s.key = 'matching_candidate_limit'
 );
