-- =============================================================================
-- المنطقة المفضّلة للسائق — البند 2.4
--
-- العطب الذي أوجبها، مقيساً على قاعدة الإنتاج: ترتيب المرشّحين يقوم على
-- `last_location` وحده — آخر موقع ورد من السائق. فالسائق الذي يسكن حيّاً ويعمل
-- فيه، إن مرّ عابراً بحيٍّ بعيد، صار في تلك اللحظة أقرب مرشّح لطلبات ذلك الحيّ،
-- ويُبعَد عن طلبات حيّه هو. وموقعه اللحظي لا يقول شيئاً عن المكان الذي يريد
-- العمل فيه — والاثنان يفترقان كل يوم في أوّل الصباح وآخر الليل.
--
-- والحلّ ليس استبدال `last_location`: القرب الفعلي هو ما يحدّد زمن الوصول،
-- ولا يُستغنى عنه. المنطقة المفضّلة عاملٌ **ثانٍ** بوزنه الخاص من
-- `platform_settings`، فتبقى موازنة العاملين قراراً تشغيلياً لا رقماً في الكود.
--
-- ما يُضاف: عمودان على `drivers` — لا جدول جديد، فلا محلّ لقاعدة `city_id`
-- هنا: الجدول يحمل `city_id not null` منذ المرحلة 2.1.
--
-- لماذا لا قيد not null؟ لأن القاعدة فيها سائق مسجَّل قبل هذا الحقل، ولأن
-- المنطقة المفضّلة **اختيارية بطبيعتها**: سائقٌ يعمل في المدينة كلّها لا منطقة
-- له، وفرضُ واحدة عليه يجعله يختار عشوائياً فيُفسد الترتيب بدل أن يُصلحه.
-- وغياب المنطقة يعني «رتّبني بالقرب وحده» — وهو سلوك المنصّة قبل هذه الهجرة
-- حرفياً، فلا يتغيّر على أحد شيء بلا اختياره.
--
-- والاسم مع الإحداثية لا الإحداثية وحدها: «حي الصفا» هو ما يفهمه السائق ويراه
-- في لوحة الإدارة؛ ونقطةٌ عشرية لا تُقرأ ولا تُراجَع ولا يُكتشف خطؤها.
-- =============================================================================

alter table drivers add column if not exists preferred_area_label     text;
alter table drivers add column if not exists preferred_area_location  geography(point, 4326);

comment on column drivers.preferred_area_label is
  'اسم المنطقة التي يفضّل السائق العمل فيها كما كتبه أو كما وصل من تلغرام — للعرض والمراجعة';
comment on column drivers.preferred_area_location is
  'مركز المنطقة المفضّلة. اختياري: غيابه يعني الترتيب بالقرب اللحظي وحده كما كان';

-- ----------------------------------------------------------------------------
-- سلامة الزوج: لا إحداثية بلا اسم ولا اسم بلا إحداثية
--
-- نصفُ منطقةٍ أسوأ من غيابها: اسمٌ بلا نقطة يظهر في لوحة الإدارة كأن المنصّة
-- تعرف مكان عمله وهي لا تحسب به شيئاً، ونقطةٌ بلا اسم تُرجَّح بها الطلبات ولا
-- يستطيع أحد أن يراجع صحّتها. والقيد يسمح بغياب الاثنين معاً — وهي الحال
-- الطبيعية لكل صفٍّ قائم اليوم.
-- ----------------------------------------------------------------------------
alter table drivers drop constraint if exists drivers_preferred_area_pair;
alter table drivers add constraint drivers_preferred_area_pair check (
  (preferred_area_label is null and preferred_area_location is null)
  or (preferred_area_label is not null and preferred_area_location is not null)
);

-- الفهرس المكاني جزئي: أكثر الصفوف بلا منطقة، وفهرسة الغياب حجمٌ بلا فائدة.
create index if not exists drivers_preferred_area_idx
  on drivers using gist (preferred_area_location)
  where preferred_area_location is not null;

-- ----------------------------------------------------------------------------
-- وزن المنطقة المفضّلة في معادلة الترتيب — من الإعدادات لا من الكود
--
-- يُبذَر بصفر في كل مدينة قائمة قصداً: صفرٌ يعني أن معادلة الترتيب اليوم هي
-- نفسها معادلة الأمس بحرفها، فلا يتغيّر ترتيبُ سائقٍ واحد بمجرّد تشغيل هجرة.
-- تفعيله قرارٌ تشغيلي يُتخذ من لوحة الإدارة بعد أن تُجمع مناطق السائقين فعلاً —
-- ووزنٌ يُفعَّل قبل أن يملك أحدٌ منطقة يجعل كل السائقين متساوين فيه، أي لا أثر
-- له إلّا استهلاك حصّة الوزنين الآخرين.
--
-- ومجموع الأوزان الثلاثة يبقى 1 بالضرورة: هو قيد رياضي لبقاء النقاط في [0,1]،
-- ولا يُملأ الوزن الجديد إلّا بخصمٍ صريح من أحد الوزنين — لا بالزيادة عليهما.
-- ----------------------------------------------------------------------------
-- ويُعلَّم `is_provisional`: القيمة صفرٌ آمن لا رأيٌ للمالك، وهو يراجعها متى شاء.
insert into platform_settings (city_id, key, value, value_type, description_ar, is_provisional)
select c.id,
       'match_weight_preferred_area',
       '0'::jsonb,
       'number',
       'وزن مطابقة المنطقة المفضّلة للسائق في معادلة الترتيب — صفرٌ يعني تجاهلها. ومجموع أوزان المطابقة الثلاثة يجب أن يساوي 1',
       true
  from cities c
 where not exists (
   select 1 from platform_settings s
    where s.city_id = c.id and s.key = 'match_weight_preferred_area'
 );
