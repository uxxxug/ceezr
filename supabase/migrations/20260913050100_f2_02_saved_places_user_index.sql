-- الحالة: مُطبَّقةٌ بالمُطبِّقِ الآمنِ في طورِ `index` بلا معاملةٍ.
-- ينتمي إلى: supabase/migrations
-- يُستخدم من: `list_saved_places` — كلُّ قراءةٍ تُرشِّحُ بـ`user_id`.
-- ما لا تفعله: لا تُغيِّرُ مخطّطاً ولا بيانةً ولا تحجبُ الكتابةَ (`concurrently`).
--
-- ## العودة (rollback)
--
-- `drop index concurrently if exists saved_places_user_idx;` — ولا تُفقَدُ بيانةٌ. ويعودُ الترشيحُ مسحاً كاملاً فيبطؤُ ولا يُخطئُ.
--
-- ## ولماذا ملفٌّ لكلِّ فهرسٍ
--
-- `create index concurrently` لا تُقبَلُ داخلَ معاملةٍ، والمُطبِّقُ الآمنُ يُرسِلُ
-- الملفَّ متعدِّدَ العباراتِ في معاملةٍ واحدةٍ — فملفٌّ لكلِّ فهرسٍ شرطُ تنفيذٍ لا
-- ذوقُ تنظيمٍ، وحاجزُ `scripts/check-migration-safety.ts` يفرضُه.
-- =============================================================================

