-- SEC-19 بندُ ٤: إسقاطُ `not null` عن `users.telegram_id`
-- ----------------------------------------------------------------------------
-- **السياقُ:** `telegram_id bigint not null unique` قائمٌ منَ الهجرةِ الأولى
-- (`20260806120000:111`). والترتيبُ المُلزِمُ (١ ← ٢ ← ٣ ← ٤) استُوفِيَ:
--
--   ١) تَحصينُ مسالكِ الإرسالِ (الخطواتُ ١–٥) — مُنضَجٌ ومُدمَجٌ.
--   ٢) `ADR 0175` + تقويةُ قيدِ `users_erased_rows_carry_no_identity` ليقبلَ
--      `telegram_id is null or telegram_id < 0` صراحةً — مُدمَجٌ (`PR #207`).
--   ٣) ربطُ `trip_tracking_tokens.created_by_user_id` بـ`users.id` — مُدمَجٌ
--      (`PR #208`).
--
-- فهذه هيَ الخطوةُ الأخيرةُ: **إسقاطُ `not null` وحدَها**.
--
-- **ما لا يُمسُّ:**
--   • الفهرسُ `unique` يَقبَلُ `null`اتٍ متعدِّدةً بلا تعديلٍ في PostgreSQL.
--   • لا تغييرَ في التواقيعِ ولا في السطحِ العلنيِّ.
--   • لا نزعَ `erased_account_telegram_seq` — الصفوفُ القائمةُ تحملُ سوالبَ
--     مُولَّدةً من المَعرِضِ، والتمثيلُ المستقبليُّ (`null`، `ADR 0175`) مسلكٌ
--     للكتاباتِ الجديدةِ لا ترحيلٌ للقديمةِ في هذا البابِ.
--   • لا ترحيلَ بياناتٍ: المُعرِّفاتُ السالبةُ القائمةُ تبقى كما هيَ.
--
-- **ما يُثبَتُ:** `pg_attribute.attnotnull = false` لعمودِ `telegram_id` في
-- `users`، وإدخالُ صفٍّ بـ`telegram_id = null` معَ `erased_at is not null`
-- يُقبَلُ — والقيدُ `users_erased_rows_carry_no_identity` يرفضُ الاسمَ والرقمَ
-- معَ الغيابِ كما قُوِّيَ في البندِ ٢.
-- ============================================================================
alter table users alter column telegram_id drop not null;

