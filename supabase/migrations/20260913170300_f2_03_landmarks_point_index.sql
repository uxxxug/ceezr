-- migration-phase: index
-- =============================================================================
-- الغرض: فهرسٌ مكانيٌّ لأقربِ معلَمٍ إلى دبّوسٍ (البند `F2-03`).
-- الحالة: مُطبَّقةٌ بالمُطبِّقِ الآمنِ في طورِ `index` بلا معاملةٍ.
-- ينتمي إلى: supabase/migrations
-- يُستخدم من: `resolve_destination` — `order by l.point <-> v_point limit 1`.
-- ما لا تفعله: لا تُستخدَمُ في فحصِ الاحتواءِ داخلَ منطقةِ الخدمةِ: ذاكَ صفٌّ واحدٌ يُقرأُ بمفتاحِه لا بمسحٍ مكانيٍّ.
--
-- ## العودة (rollback)
--
-- `drop index concurrently if exists destination_landmarks_point_idx;` — بلا فقدِ بيانةٍ؛ يصيرُ ترتيبُ الجارِ الأقربِ مسحاً على عشرةِ صفوفٍ.
--
-- ## ولماذا `gist` لا `btree`
--
-- `<->` عاملُ مسافةٍ مكانيٍّ لا مقارنةُ ترتيبٍ، ولا يخدمُه `btree` أصلاً. وهوَ وحدَه ما يجعلُ «أقربُ معلَمٍ» قراءةَ جارٍ لا فرزاً لكلِّ الصفوفِ حينَ يكبرُ الدليلُ من عشرةٍ إلى آلافٍ.
-- =============================================================================

create index concurrently if not exists destination_landmarks_point_idx
  on destination_landmarks using gist (point);
