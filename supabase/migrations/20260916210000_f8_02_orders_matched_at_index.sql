-- ## لِمَ فهرسٌ لمقياسٍ
--
-- استعلامُ `/metrics` يُنفَّذُ عندَ كلِّ مسحٍ، وثلاثةُ استعلاماتٍ فرعيّةٍ منه
-- تُرشِّحُ بـ`matched_at >= now() - 5 min`. وبلا فهرسٍ **يُمسَحُ جدولُ الطلباتِ
-- كلُّه كلَّ مسحةٍ**، فينمو ثمنُ المراقبةِ بنموِّ التاريخِ: المراقبةُ تصيرُ هيَ
-- أثقلَ استعلامٍ دوريٍّ في القاعدةِ. والفهرسُ **جزئيٌّ** (`matched_at is not
-- null`) فلا يحملُ الطلباتِ الباحثةَ ولا الملغاةَ التي لا تدخلُ القياسَ أصلاً.
--
-- و`created_at` مُدرَجٌ في الفهرسِ (`include`) كي يُحسَبَ الفارقُ من الفهرسِ
-- نفسِه متى سمحَ المُخطِّطُ بمسحٍ يقتصرُ عليه، فلا تُزارُ الكومةُ لصفٍّ لا يُقرأُ
-- منه غيرُ ختمَينِ.

create index concurrently if not exists orders_matched_at_idx
  on orders (matched_at) include (created_at)
  where matched_at is not null;
