-- ============================================================================
-- المرحلة ٨ — عمرُ الموقع المقبول في الإسناد: driver_location_max_age_seconds
--
-- ## العطب المُقاس قبل هذه الهجرة
--
-- `rejectionReasonFor` تفحص المدينة والحجب والتوثيق والتوفّر وغياب الموقع
-- والقدرة والاشتراك ونصف القطر — ولا تفحص **عمر** الموقع. فسائقٌ أرسل موقعه
-- عند الفجر وبقي `is_available = true` يُحسب عند الظهر واقفاً في نفس النقطة،
-- فتُقاس مسافته من التقاطٍ لا يمتّ إلى مكانه بشيء، ويُبثّ إليه الطلب.
--
-- والضرر ليس نظرياً ولا يقع على السائق وحده: العميل يرى «سائقٌ على بُعد
-- كيلومترين» ويقبل، فيصل سائقٌ كان في الحقيقة على بُعد عشرين. والنقاط تُرتّب
-- بنصف حسابها (وزن القرب) على معطىً كاذب، فترتيبُ الدفعة نفسه غير صحيح — لا
-- الأوّل فيها أقرب من الثالث.
--
-- وأُثبِت العطب باختبارٍ سقط قبل الإصلاح: مرشّح موقعه عمره ستّ ساعات أعاد
-- `null` أي «مؤهَّل».
--
-- ## لماذا إعدادٌ للمدينة لا ثابتٌ في الكود
--
-- العمرُ المقبول قرارٌ تشغيلي يختلف بالمدينة وبنمط السائقين فيها: مدينةٌ
-- سائقوها يشاركون موقعاً حيّاً متّصلاً تكفيها دقائق، ومدينةٌ يرسل سائقوها نقطةً
-- ساكنة مرّةً عند التوافر تحتاج مدىً أوسع. وترميزه في الكود يعني نشراً لكل
-- ضبط — وهو بالضبط ما تتجنّبه `platform_settings` في كل معامل مطابقةٍ آخر.
--
-- ولا مصدرَ ثانياً للحقيقة: `DEFAULT_SESSION_POLICY.staleAfterSeconds` (٣٠
-- ثانية) موجودة أصلاً، ولا تُعاد استخدامها هنا **قصداً** لأنها تجيب سؤالاً
-- آخر — «هل نرسم هذا السائق على خريطة العمليات الآن؟». خريطةٌ تُحدَّث كل ثانية
-- تتحمّل حدّاً بثلاثين ثانية؛ وإسنادٌ يُقاس بها كان سيُسقط كل سائقٍ لا يبثّ
-- بثّاً حيّاً، أي أكثر السائقين. فالسؤالان مختلفان، والقيمةُ الواحدة لهما كانت
-- ستجعل ضبط أحدهما يفسد الآخر بلا أن يُلاحظ.
--
-- ## ولماذا يُبذَر صفراً — أي معطّلاً
--
-- صفرٌ يعني «لا حدّ للعمر»، أي أن سلوك الإسناد بعد هذه الهجرة هو سلوكه قبلها
-- **بحرفه**: لا سائقَ واحدٌ يفقد أهليّته بمجرّد تشغيل هجرة. وهذا نفس ما فُعِل
-- بـ`match_weight_preferred_area` ولنفس السبب: حدٌّ يُفعَّل بلا قياسٍ لنمط
-- السائقين الحقيقي قد يُفرِّغ الدفعة في مدينةٍ كاملة، وانقطاعُ الإسناد أسوأ من
-- إسنادٍ بموقعٍ قديم — الأول يوقف العمل، والثاني يُخطئ في تقديره.
--
-- فالحَرَس يُسلَّم مُختبَراً ومُعطَّلاً، وتفعيله قرارُ المالك من لوحة الإدارة
-- بعد أن يُقاس متوسط الفترة بين إصلاحتين لسائقٍ متاح. ولذلك `is_provisional`.
--
-- ## المرجع الزمني: `last_location_at` لا `last_location_recorded_at`
--
-- العمرُ يُقاس بزمن **الخادم** لحظةَ الكتابة لا بالطابع الذي أرسله الجهاز.
-- والفرق حاسم: طابع الجهاز مُدخَلٌ من الخارج يمكن أن يكون مضبوطاً خطأً أو
-- مُزوَّراً، فسائقٌ ساعتُه متقدّمة ساعةً يبدو موقعُه أحدثَ مِن كل من حوله إلى
-- الأبد. والسؤال هنا «متى عرفنا؟» لا «متى يقول إنه كان؟» — والجواب الأول عندنا
-- وحدنا ولا يُزوَّر.
-- ============================================================================

insert into platform_settings (city_id, key, value, value_type, description_ar, is_provisional)
select c.id,
       'driver_location_max_age_seconds',
       '0'::jsonb,
       'number',
       'أقصى عمرٍ مقبول لموقع السائق ليدخل الإسناد، بالثواني. صفرٌ يعني تعطيل الفحص — ويُقاس بزمن استقبال الخادم لا بطابع الجهاز',
       true
  from cities c
 where not exists (
   select 1 from platform_settings s
    where s.city_id = c.id and s.key = 'driver_location_max_age_seconds'
 );

-- ----------------------------------------------------------------------------
-- فهرس يخدم الفحص الجديد
--
-- استعلام المرشّحين يقرأ كلّ سائقي المدينة ثم يُرشِّح في الدومين (قرارٌ قائم:
-- الاستبعاد بسببٍ مُسمّى لا اختفاءٌ صامت في SQL). فالفهرس هنا ليس للترشيح بل
-- لقراءات العمليات التي تسأل «من موقعُه حديث في هذه المدينة؟» — وهي القراءة
-- التي تنمو مع عدد السائقين لا مع عدد الطلبات.
-- ----------------------------------------------------------------------------
create index if not exists drivers_city_location_at_idx
  on drivers (city_id, last_location_at desc nulls last)
  where last_location is not null;

comment on index drivers_city_location_at_idx is
  'المرحلة ٨ — يخدم سؤال «من موقعُه حديث في هذه المدينة؟». جزئي: من لا موقع له لا يُسأل عن عمره.';
