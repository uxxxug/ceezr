-- المرحلة ٥ — فصل «متى كان السائق هناك» عن «متى علمنا».
--
-- `last_location_at` تُكتب بـ`now()`، أي زمن الخادم لحظةَ الكتابة. وهي القيمة
-- الصحيحة لسؤال «هل معرفتنا حديثة؟». لكنها القيمة **الخاطئة** لقياس التتابع.
--
-- والخطأ ظهر قياساً لا تحليلاً: إصلاحتان بينهما ٢٥٠ متراً وستون ثانية — أي ١٥
-- كم/سا، مشيٌ سريع — حُكم عليهما بـWARNING. لأن الطابع الجديد زمنُ جهاز والطابع
-- السابق زمنُ خادم، فالمدة المقيسة بينهما كانت صفراً تقريباً، و٢٥٠ متراً في صفر
-- ثانية سرعةٌ لا نهائية.
--
-- ومقارنة ساعتين مختلفتين لا تُصلَح بمعامل تصحيح: الفارق بينهما هو زمن الشبكة
-- والطابور، وهو متغيّر بطبيعته. فالحلّ أن يُحفظ زمن الجهاز كما هو، وتُقاس
-- الإزاحة بين زمنَي جهازٍ لا بين جهازٍ وخادم.
--
-- والعمودان ليسا تكراراً: أحدهما واقعة عن السائق، والآخر واقعة عن نظامنا.
-- تباعدهما الكبير معلومة مفيدة بذاتها (جهاز يُرسل دفعةً بعد انقطاع).

alter table drivers
  add column if not exists last_location_recorded_at timestamptz;

comment on column drivers.last_location_at is
  'زمن الخادم لحظة قبول الإصلاحة — «متى علمنا». لقياس حداثة المعرفة.';

comment on column drivers.last_location_recorded_at is
  'زمن جهاز السائق للإصلاحة — «متى كان هناك». أساس قياس الإزاحة والسرعة (المرحلة ٥).';

-- زمن جهازٍ يسبق وجود الصفّ نفسه بأسابيع لا يُقاس عليه شيء. القيد فضفاض عمداً:
-- غرضه منع القيم الفاسدة تماماً (طابع صفري، أو 1970) لا ضبط انحراف الساعات —
-- فذلك حكمٌ نسبيّ يخصّ المُقيِّم في المجال، لا قيداً مطلقاً في القاعدة.
alter table drivers
  drop constraint if exists drivers_last_location_recorded_at_sane;

alter table drivers
  add constraint drivers_last_location_recorded_at_sane
  check (
    last_location_recorded_at is null
    or last_location_recorded_at > timestamptz '2020-01-01'
  );
