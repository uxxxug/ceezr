-- =============================================================================
-- ملفّ السائق التوثيقي: الهوية وصورة المركبة، وقيدٌ على ما كان بلا قيد
--
-- ما كان قائماً: عمودا vehicle_type وplate_number موجودان في الجدول منذ
-- المرحلة 2.1 — **ولا سطر واحد في المنصّة يكتب فيهما**. تسجيل السائق ينتهي
-- عند اختيار الخدمة، فيُوثَّق سائقٌ لا يُعرف ما يقود ولا رقم لوحته ولا من هو.
--
-- ما يُضاف: رقم الهوية/الإقامة، ومعرّف صورة المركبة في تيليجرام.
--
-- الصورة تُخزَّن بمعرّفها (file_id) لا كملف: تيليجرام يحفظها ويخدمها، وتنزيلها
-- إلى تخزيننا يعني نسخةً ثانية من وثيقة شخصية نتحمّل حراستها بلا داعٍ.
--
-- الهوية بيانات شخصية: يُمنع طبعها في أي سجل، ولا تُعاد في أي واجهة عامة.
-- وصولها محصور بموظّف التوثيق عبر لوحة الإدارة.
--
-- لماذا لا قيد not null؟ لأن في القاعدة سائقاً مسجَّلاً قبل هذا الحقل. فرضُ
-- القيد كان سيُسقط الهجرة أو يُلفّق له قيمة كاذبة. الاكتمال يُفرَض في مسار
-- التسجيل وقبل التوثيق، لا بقيدٍ يكسر ما هو قائم.
-- =============================================================================

alter table drivers add column if not exists national_id            text;
alter table drivers add column if not exists vehicle_photo_file_id  text;

comment on column drivers.national_id is
  'رقم الهوية الوطنية أو الإقامة — بيانات شخصية: لا تُطبع في أي سجل ولا تُعاد في واجهة عامة';
comment on column drivers.vehicle_photo_file_id is
  'معرّف صورة المركبة في تيليجرام (file_id) — لا نُخزّن الملف نفسه';

-- البحث عن سائق برقم هويته حاجةٌ حقيقية لموظّف التوثيق عند ورود بلاغ.
create index if not exists drivers_national_id_idx
  on drivers (national_id) where national_id is not null;

-- ----------------------------------------------------------------------------
-- منع ازدواج الهوية داخل المدينة الواحدة
--
-- شخصٌ واحد بحسابين تيليجرام يفتح بابين: تجربتان مجّانيتان بدل واحدة، وسائقٌ
-- محظور يعود بحساب جديد. الهوية هي الرابط الوحيد الثابت بين الحسابين.
--
-- ولماذا داخل المدينة لا على مستوى المنصّة؟ لأن سائقاً ينتقل من جدة إلى
-- الرياض حالةٌ مشروعة، ومنعه من التسجيل في مدينته الجديدة عقوبةٌ بلا ذنب.
-- والقيد الفريد الجزئي يتجاهل الصفوف الفارغة، فلا يمسّ السائق القائم.
-- ----------------------------------------------------------------------------
create unique index if not exists drivers_city_national_id_uniq
  on drivers (city_id, national_id) where national_id is not null;
