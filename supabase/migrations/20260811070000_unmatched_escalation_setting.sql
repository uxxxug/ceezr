-- عتبة تصعيد الطلب غير المُطابَق — إعداد لكل مدينة لا ثابت في الكود
--
-- قبل هذه المهمة كان الطلب الذي لا يجد سائقاً يسقط بين مهمّتين: expire-offers
-- لا تجد عرضاً لتُنهي مهلته، وrotate-negotiations لا تجد دورةً لتُدوّرها. فيبقى
-- 'searching' بلا نهاية، وصاحبه ينتظر بلا كلمة حتى يلغي بنفسه.
--
-- ولماذا إعداد لا ثابت؟ لأن "كم ينتظر الراكب قبل أن نقول له لا يوجد سائق" قرار
-- تجاري يخصّ كل مدينة: المدينة المزدحمة تحتمل انتظاراً أطول لأن سائقاً سيظهر،
-- والمدينة الصغيرة يُهدر فيها الانتظار. جعله إعداداً يمنح المالك تغييره بلا نشر.
--
-- القيمة الافتراضية 180 ثانية: أطول من دورة بثّ واحدة (مهلة العرض 45 ثانية)
-- بما يكفي لئلا نصعّد طلباً كان سيُلتقط، وأقصر من صبر إنسانٍ ينتظر بلا خبر.
-- =============================================================================

insert into platform_settings (city_id, key, value, value_type, description_ar, is_provisional)
select c.id,
       'unmatched_escalate_after_seconds',
       to_jsonb(180),
       'number',
       'المدة بالثواني قبل تصعيد طلب لم يجد أي سائق إلى قروب الإسناد وإشعار صاحبه',
       true
  from cities c
on conflict (city_id, key) do nothing;
